def describe(category: str, value: object) -> EntryDict:
    """Подпись одного значения: {"label","hint","action"}.

    Безопасный запасной путь для неизвестного кода: label = сам код, hint и
    action пустые. Реальные значения перечислений до него доходить не должны
    (это проверяет тест полноты). Копия возвращается, чтобы вызывающий код не
    мог испортить словарь.
    """
    table = LABELS.get(category)
    key = value if isinstance(value, str) else str(value)
    entry = table.get(key) if table is not None else None
    if entry is None:
        return {"label": key, "hint": "", "action": ""}
    return dict(entry)


def glossary() -> dict[str, dict[str, EntryDict]]:
    """Весь словарь (для страницы «Справка»): категория → значение → подписи."""
    return {category: {value: dict(entry) for value, entry in table.items()} for category, table in LABELS.items()}


