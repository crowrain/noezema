#: ослаблены ни на пункт: страницы, называющие Минэкономразвития наряду с другим
#: первоисточником, переходят в `ambiguous_primaries` — тот же консервативный выход, что дал
#: v4 на страницах с двумя первоисточниками. Решения v6 отличаются от решений v5 →
#: переатрибуция пересматривает страницы эпохи v5 (`apps/research_proxy/reattribution.py`).
#: v7 (T7.110): в шаблоне глагола ожидания `RELAY_FORECAST_VERBS` исправлена латинская «o»
#: после `\b` (омоглиф U+006F вместо кириллической «о», жил с T7.98): реле-кандидаты по
#: «ожидает/ожидали» заговорили. Решения по всем фикстурным текстам репозитория не изменились
#: (замер свипа), решения на текстах с названным ожиданием меняются в консервативную сторону
