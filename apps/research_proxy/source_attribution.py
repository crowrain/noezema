#: отличаются от решений v6 → переатрибуция пересматривает страницы эпохи v6.
#: v8 (T7.112 (а3), стендовый случай 4e7ba8c2): словарь шаблонов дополнен глаголами отчётности
#: первоисточника — «зафиксировал…», «обнародовал…», «опубликовал…», «отчитал(ся|ась|ись)»
#: (закрытый список, совершенный вид прошедшего времени; причастия и настоящее время — нет).
#: Правило пары не ослаблено: значение + шаблон + алиас в окне одного фрагмента. Перечитывание
#: испорченных нормализованных текстов из оригиналов с объявленной не-UTF-8 кодировкой (а2)
#: происходит на стороне переатрибуции (`apps/research_proxy/reattribution.py`), решение принимает
#: этот метод по живому тексту страницы. Решения v8 отличаются от решений v7 (замер свипа —
#: STATUS T7.112) → переатрибуция пересматривает страницы эпохи v7.
#: v9 (T7.120, решение пользователя 2026-10-17): словарь дополнен десятью негосударственными
