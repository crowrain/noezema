#: v3 (T7.85): словарь и шаблоны расширены по замерам живых страниц подставки (замеры —
#: docs/STATUS.md, раздел T7.85): «следует из данных Росстата» (expert.ru, ria.ru),
#: репортажные формы «ЦБ сообщил» (заголовок forbes.ru) и «из сообщения Росстата», голое
#: «ЦБ» без «РФ». Правило пары не изменилось: значение + шаблон + измеренное число + алиас
#: в одном фрагменте и в окне ATTRIBUTION_WINDOW_CHARS — расширен только словарь, поэтому
#: решения v3 отличаются от решений v2 и переатрибуция обязана их пересмотреть.
#: v4 (T7.98, стендовый дефект ca2484b2): добавлен relay-кандидат — «первоисточник + его
#: глагол прогноза + значение» в одном фрагменте без шаблона атрибуции
#: (`_relay_forecast_keys`, ADR-0029 дополнение). Страница, пересказывающая прогноз
#: первоисточника без шаблона («Банк России повысил прогноз инфляции на 2026 год до 6–7%»),
#: больше не остаётся однобокой: если на ней есть и другой первоисточник, решение —
#: `ambiguous_primaries`, указатель не ставится. Шаблонный pairing не ослаблен ни на пункт:
#: relay только добавляет кандидатов в тот же словарь. Решения v4 отличаются от решений v3 →
#: переатрибуция пересматривает страницы эпохи v3, включая снятие прежнего указателя там,
#: где свежий метод увидел два первоисточника (`apps/research_proxy/reattribution.py`).
#: v5 (T7.107, стендовый дефект 7cfbe942/smart-lab): вето собственной оценки проверяется по
#: копии скан-текста, из которой убраны фразы ЗАКРЫТОГО списка шаблонных оговорок площадок
#: (`SITE_DISCLAIMER_PHRASES`, `mask_site_disclaimers`) — плашка «Мнение владельца сайта может
#: не совпадать с мнением автора» больше не делает блог самостоятельным исследованием. Словарь
#: маркеров собственной оценки НЕ сокращён: настоящая оценка («…не совпадает с данными
#: Росстата») по-прежнему даёт `own_assessment`. Хранимый текст и его хеш не меняются: маска
#: живёт только на копии для вето. Решения v5 отличаются от решений v4 → переатрибуция
#: пересматривает страницы эпохи v4 (`apps/research_proxy/reattribution.py`).
#: v6 (T7.109, решение пользователя 2026-10-13): в словарь добавлена запись «Минэкономразвития
#: России» (ключ `minec`, домашний хост economy.gov.ru; Минфин — отдельная запись), и сравнение
#: чисел стало равнозначным по хвостовым нулям дробной части (`_canonical_number`: 7,0 ≡ 7,
