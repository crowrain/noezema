#: глаголы фиксации/измерения числа (пункт «глагол» замечания приёмки). Сам по себе такой глагол
#: действующим лицом НЕ является: публикация первоисточника и состоит из измерений («Росстат
#: показал 5,59%», «Банк России зафиксировал оценку на уровне 14,5%»), и голое вето по глаголу
#: убило бы сам оконный режим. Поэтому глагол — признак ТОЛЬКО как действие другого лица: он должен
#: стоять вплотную (через один пробел) к НЕ замазанному имени собственному — перед ним или после
#: него («ВЦИОМ зафиксировал», «зафиксировала ФОМ»). Алиас словаря замазан вместе с именем, и
#: на его месте остаются ПРОБЕЛЫ ДЛИНОЙ С ИМЯ: соседства «имя␠глагол» больше нет → вето молчит.
#: Именно поэтому контроль «сам первоисточник» работает: «Росстат показал…» и
#: «Банк России зафиксировал…» — первоисточник, а не чужое действующее лицо. Границу предложения
#: связкой пересечь нельзя: между именем и глаголом нет ни точки, ни второго оборота.
OTHER_SOURCE_FIXATION_MARKERS: Final[tuple[str, ...]] = (
    r"\bзафиксир\w*",  # зафиксировал/зафиксировала/зафиксировано
    r"\bпоказ(?:ал[а-яё]*|ыва[а-яё]*)",  # показал/показали/показывали («показатель» — мимо: см. ниже)
    r"\bнасчита\w*",  # насчитал/насчитали
    r"\bвыясн\w*",  # выяснил/выясняли/выяснили
    r"\bизмер(?:и\w*|я\w*)",  # измерил/измеряли
    r"\bзамер(?:и\w*|я\w*)",  # замерил/замеряли
    r"\bзарегистрир\w*",  # зарегистрировал/зарегистрировали (как действие другого лица)
    r"\bподсчита\w*",  # подсчитал/подсчитали
)

#: имя собственное в позиции действующего лица. `[А-ЯЁ]` в начале обязательно и IGNORECASE здесь
#: НЕ применяется: без заглавной буквы это обычное слово, а не имя («исследование показало» — не
#: чужой источник). Имя из белого списка показателей/географии актором не считается.
_NAME_SLOT: Final = r"[А-ЯЁ][А-ЯЁA-Za-zа-яё]{1,60}"
_FIXATION_VERBS: Final = "|".join(OTHER_SOURCE_FIXATION_MARKERS)

#: название организации в кавычках вне начала предложения (пункт «кавычки» замечания приёмки).
#: Заглавные слова БЕЗ кавычек проверяются только как аббревиатуры (T7.85b: ≥2 заглавных букв) и
#: только в связке «имя␠глагол» для глагола фиксации: слишком много ложных срабатываний дало бы
#: начало предложения и имена показателя; риск описан в STATUS T7.85a/T7.85b и ADR-0029.
_QUOTED_NAME: Final = re.compile(r"«([^»\n]{1,60})»|\"([^\"]{2,60})\"")
_SURVEY_CUSTOMER: Final = tuple(
    re.compile(pattern)  # без IGNORECASE: заглавная буква имени — часть признака
    for pattern in SURVEY_WITH_ANOTHER_CUSTOMER_MARKERS
)
#: связка «имя собственное␠глагол фиксации» и обратная «глагол␠имя»: ровно один пробел, без
#: IGNORECASE. «Ровно один» — не косметика: замазанный алиас оставляет пробелы длиной с имя, и
#: соседство через них становится невозможным; именно это держит «Росстат показал» чистым
#: (см. комментарий к `OTHER_SOURCE_FIXATION_MARKERS`).
_SUBJECT_THEN_VERB: Final = re.compile(rf"(?P<subject>{_NAME_SLOT}) (?P<verb>(?:{_FIXATION_VERBS}))\b")
_VERB_THEN_SUBJECT: Final = re.compile(rf"(?P<verb>(?:{_FIXATION_VERBS})) (?P<subject>{_NAME_SLOT})\b")
_SENTENCE_BREAK: Final = re.compile(r"[.!?\u2026]+")

#: какой pairing дал решение — записывается в улику, чтобы более слабый режим был виден оператору.
#: Словарь значений и проверка формы живёт в одном месте — `packages/memory/scope.py`
#: (`VALUE_ATTRIBUTION_PAIRINGS`): у детектора и у записи не должно быть двух мнений о том,
#: как называется режим pairing.
PAIRING_VALUE_AND_PRIMARY: Final = VALUE_ATTRIBUTION_PAIRING_STRICT
PAIRING_PUBLICATION_WINDOW: Final = VALUE_ATTRIBUTION_PAIRING_PUBLICATION
#: третий, самый узкий режим pairing (T7.107, ADR-0029 дополнение)
PAIRING_BIBLIOGRAPHY_KNOWN_PRODUCER: Final = VALUE_ATTRIBUTION_PAIRING_BIBLIOGRAPHY


@dataclass(frozen=True)
class ValueAttributionDecision:
    """Что хост понял о происхождении **этого значения**: чей пересказ читает утверждение."""

    status: str
    primary_key: str | None = None
    primary_name: str | None = None
    parent_uri: str | None = None
    #: фрагмент, на котором основано решение (маскированный, обрезанный — как у страничного детектора)
    basis_fragment: str = ""
    #: значения утверждения, по которым выбран фрагмент; пусто — когда утверждение не называет
    #: измеренного значения, и тогда выбор идёт по всему основанию улики (строже к отказу)
    claim_values: tuple[str, ...] = ()
    #: какой pairing дал решение: строгий режим или окно публикации (T7.78/T7.85). Записывается
    #: в улику (`packages/memory/scope.py`), чтобы более слабое основание было видно оператору
    pairing: str = PAIRING_VALUE_AND_PRIMARY

    @property
    def is_derivative(self) -> bool:
        return self.status == STATUS_DERIVATIVE


def _measured_numbers(text: str) -> set[str]:
    """Числа текста, которые являются значениями: число с единицей измерения рядом."""
    found: set[str] = set()
    for match in VALUE_NUMBER_PATTERN.finditer(text):
        tail = text[match.end() : match.end() + _UNIT_TAIL_CHARS]
        if _UNIT_SCAN.match(tail):
            found.add(_canonical_number(match.group()))
    return found


#: T7.109 (часть а): соединитель диапазона в утверждении — дефис, короткое или длинное тире
#: (могут быть окружены пробелами) либо слово «до». Один пробельный промежуток: «6 до 7%» —
#: диапазон; «6 рублей до 7%» — уже не соединитель, а текст между числами.
_RANGE_CONNECTOR: Final = re.compile(r"[ ]{0,3}[-\u2013\u2014][ ]{0,3}|[ ]+до[ ]+")
#: конец диапазона обязан читаться как одно десятичное число («3.2.5» диапазоном не становится)
_SIMPLE_CANONICAL: Final = re.compile(r"\d+(?:\.\d+)?")
#: разделитель составного токена диапазона (T7.109a): канонические формы левого и правого конца,
#: склеенные через него. Символ не встречается в выводе `_canonical_number`
#: (`VALUE_NUMBER_PATTERN` не читает «-»), поэтому составной токен не может совпасть с
#: одиночным числом: сравнение диапазонов работает только через него.
_RANGE_TOKEN_SEP: Final = "-"


def _range_value_spans(text: str) -> list[tuple[int, int, str]]:
    """Диапазоны ТЕКСТА (T7.109a) — те же условия, что диапазонная ветка `_claim_measured_numbers`:
    соединитель вплотную между концами (`_RANGE_CONNECTOR`), у левого конца нет своей единицы
    (иначе это уже измеренное число: «6,0% – 7,0%» — пара замеров, не диапазон), единица стоит
    после правого конца, оба конца читаются как одно десятичное число. Возвращает кортежи
    (позиция левого конца, позиция после правого, составной канонический токен). Диапазон
    страницы — ОДНО значение: его концы не самостоятельные измеренные числа."""
    spans: list[tuple[int, int, str]] = []
    tokens = list(VALUE_NUMBER_PATTERN.finditer(text))
    for index, left in enumerate(tokens):
        if index + 1 >= len(tokens):
            continue
        left_tail = text[left.end() : left.end() + _UNIT_TAIL_CHARS]
        if _UNIT_SCAN.match(left_tail):
            continue  # у левого конца своя единица: он уже измеренное число, не начало диапазона
        canonical_left = _canonical_number(left.group())
        if not _SIMPLE_CANONICAL.fullmatch(canonical_left):
            continue  # токен не читается как число: диапазона из него не собирают
        right = tokens[index + 1]
        if not _RANGE_CONNECTOR.fullmatch(text[left.end() : right.start()]):
            continue  # концы не смежны: это не диапазон
        right_tail = text[right.end() : right.end() + _UNIT_TAIL_CHARS]
        if not _UNIT_SCAN.match(right_tail):
            continue  # единица стоит не после правого конца: значения в диапазоне нет
        canonical_right = _canonical_number(right.group())
        if not _SIMPLE_CANONICAL.fullmatch(canonical_right):
            continue  # правый конец тоже обязан читаться как одно число
        spans.append(
            (left.start(), right.end(), f"{canonical_left}{_RANGE_TOKEN_SEP}{canonical_right}")
        )
    return spans


def _measured_value_tokens(text: str) -> frozenset[str]:
    """Измеренные значения ТЕКСТА с учётом диапазонов (T7.109a): одиночные измеренные числа
    плюс диапазоны целиком (составной токен); концы диапазона одиночными числами не становятся —
    правый конец «6-7%» — это не «7», а значение «6-7». Правило действует с обеих сторон:
    одиночное значение утверждения приписывается только одиночному числу текста (число,
    стоящее в тексте одиночно, например «…граница прогноза 7%…», по-прежнему приписывается),
    диапазон утверждения совпадает только с диапазоном текста с теми же концами."""
    ranges = _range_value_spans(text)
    values: set[str] = {token for _start, _end, token in ranges}
    for match in VALUE_NUMBER_PATTERN.finditer(text):
        tail = text[match.end() : match.end() + _UNIT_TAIL_CHARS]
        if not _UNIT_SCAN.match(tail):
            continue  # число без единицы — не значение (тот же измеритель, что у `_measured_numbers`)
        if any(start <= match.start() and match.end() <= end for start, end, _token in ranges):
            continue  # конец диапазона: не самостоятельный замер (T7.109a)
        values.add(_canonical_number(match.group()))
    return frozenset(values)


def claim_match_values(claim_statement: str | None) -> frozenset[str]:
    """Значения утверждения для СРАВНЕНИЯ (T7.109a): одиночные измеренные значения утверждения и
    его диапазоны составными токенами. В отличие от `claim_value_numbers` концы диапазона не
    становятся самостоятельными значениями: конец диапазона утверждения сопоставляется только с
    концом другого диапазона — и никогда с одиночным числом страницы (ложная склейка консенсуса
    «7,0%» с правым концом диапазона ЦБ «(6-7%)» на interfax_1121468 — то, что правится). Плоский
    список (`claim_value_numbers`) остаётся для записи улики, текстового гейта T7.108a и позиций
    гварда (е) relay — «значения ли это фрагмента» решает этот набор."""
    if not claim_statement:
        return frozenset()
    return _measured_value_tokens(normalize_scan_text(claim_statement))


def _claim_measured_numbers(text: str) -> set[str]:
    """Значения утверждения: измеренные числа (`_measured_numbers`) плюс оба конца диапазона
    (T7.109, решение пользователя 2026-10-13): «прогноз 6,0–7,0%», «6–7%», «от 6 до 7%» несут и
    6, и 7 — когда единица измерения стоит после ПРАВОГО конца («6,0–7,0%»: единица у правого
    конца, оба конца значения; «2025–2026 год»: единицы нет ни у одного конца — годы, не
    значения). Соединитель обязан стоять вплотную между концами: между ними не может быть других
    слов. Левый конец без своей единицы учитывается один раз: правый конец уже измерен обычно.

    Только сторона УТВЕРЖДЕНИЯ. На стороне текста измерительный критерий прежен
    (`_measured_numbers`): диапазон без единицы у левого конца остаётся одним числом с единицей
    — ложный пропуск безопаснее ложной склейки (AGENTS §7, T7.98)."""
    found = _measured_numbers(text)
    tokens = list(VALUE_NUMBER_PATTERN.finditer(text))
    for index, left in enumerate(tokens):
        left_tail = text[left.end() : left.end() + _UNIT_TAIL_CHARS]
        if _UNIT_SCAN.match(left_tail):
            continue  # у левого конца своя единица: он уже учтён общим измерителем
        canonical_left = _canonical_number(left.group())
        if not _SIMPLE_CANONICAL.fullmatch(canonical_left):
            continue  # токен не читается как число: диапазона из него не собирают
        if index + 1 >= len(tokens):
            continue
        right = tokens[index + 1]
        if not _RANGE_CONNECTOR.fullmatch(text[left.end() : right.start()]):
            continue  # концы не смежны: это не диапазон
        right_tail = text[right.end() : right.end() + _UNIT_TAIL_CHARS]
        if not _UNIT_SCAN.match(right_tail):
            continue  # единица стоит не после правого конца: значения в диапазоне нет
        found.add(canonical_left)
        found.add(_canonical_number(right.group()))
    return found


def claim_value_numbers(statement: str | None) -> tuple[str, ...]:
    """Значения утверждения (детерминированно, тем же сравнением чисел). Пусто — когда утверждение
    не называет измеренного значения: тогда выбор фрагмента идёт по всему основанию улики, и отказ
    при двух первоисточниках становится строже.

    T7.108a: этим же числом пользуется текстовый гейт «значение на связи»
    (`claim_values_found_in_texts`): с T7.109 оба конца диапазона утверждения участвуют и в
    проверке связи, и в атрибуции — сравнение чисел у гейта и детекторов одно (`_canonical_number`)."""
    if not statement:
        return ()
    return tuple(sorted(_claim_measured_numbers(normalize_scan_text(statement))))


# ─── T7.108a (ADR-0034 §10): текстовые формы значения для гейта «значение на связи» ──────
#
# Поиск значения по стороне ТЕКСТА идёт не жадными токенами `VALUE_NUMBER_PATTERN`: жадный
# токен склеивает соседние ячейки таблицы («2026 2,3 2,2» — строка таблицы Росстата)
# через пробел, табуляцию, перевод строки и точку в один токен и тем самым прячет значение,
# которое на странице стоит. Решения детекторов атрибуции (`_measured_numbers`,
# `claim_value_numbers`, гварды relay), их версии и сам `VALUE_NUMBER_PATTERN` не изменены:
# текстовые формы читает только гейт (`claim_values_found_in_texts`).

_DECIMAL_SEPARATORS: Final = ".,"
#: хвостовые нули дробной части в тексте: 2,2 ≡ 2,20; принимаются и более длинные хвосты
#  (до потолка включительно).
_MAX_TRAILING_ZEROS: Final = 3


def _grouped_digits(digits: str) -> tuple[str, ...]:
    """Формы целого числа: голые цифры и группы по три цифры через одиночный пробел
    («1649» → «1649», «1 649»). После `normalize_scan_text` в тексте не остаётся
    неразрывных и узких пробелов — они уже становятся обычными, поэтому пробел — единственный
    видный гейту разделитель группировки. Группировка ровно по три цифры: «16 49» — не форма
    числа 1649."""
    if len(digits) < 4:
        return (digits,)
    groups: list[str] = []
    rest = digits
    while len(rest) > 3:
        groups.insert(0, rest[-3:])
        rest = rest[:-3]
    groups.insert(0, rest)
    return (digits, " ".join(groups))


def _value_text_forms(value: str) -> tuple[str, ...]:
    """Способы записать это каноническое значение в тексте: десятичный разделитель «.» или «,»;
    хвостовые нули дробной части необязательны (2,2 ≡ 2,20); целая часть и целые значения —
    с группировкой разрядов по три цифры («1 649» ≡ «1649»). Значение с несколькими точками
    (патологический склеенный токен на стороне утверждения) остаётся пословным: каждая точка
    заменяется «.» или «,», группировки и хвостовых нулей к нему не применяется.
    """
    parts = value.split(".")
    if not all(part.isdigit() for part in parts):
        return (value,)  # защитный путь: каноника не чисто цифровая — только дословное совпадение
    if len(parts) > 2:
        tails: list[str] = [""]
        for part in reversed(parts[1:]):
            tails = [sep + part + tail for tail in tails for sep in _DECIMAL_SEPARATORS]
        return tuple(parts[0] + tail for tail in tails)
    head_forms = _grouped_digits(parts[0])
    frac_min = parts[1].rstrip("0") if len(parts) == 2 else None
    forms: list[str] = []
    for head_form in head_forms:
        if frac_min:
            for zeros in range(0, _MAX_TRAILING_ZEROS + 1):
                for sep in _DECIMAL_SEPARATORS:
                    forms.append(f"{head_form}{sep}{frac_min}{'0' * zeros}")
        else:
            forms.append(head_form)  # целое (или нулевая дробь): голое число — законная запись
            for zeros in range(1, _MAX_TRAILING_ZEROS + 1):
                for sep in _DECIMAL_SEPARATORS:
                    forms.append(f"{head_form}{sep}{'0' * zeros}")
    return tuple(forms)


def _form_is_standalone(text: str, start: int, end: int, *, glued_space: bool) -> bool:
    """Отдельно стоящая запись значения: перед формой нет цифры и нет пары «цифра + разделитель»
    (это хвост другого числа: «122,2», «12,2», «3.2»), после формы нет цифры и нет пары
    «разделитель + цифра» (это начало другого числа: «2,21», «2,2.5»). Пробел, табуляция,
    перевод строки и точка с пробелом ПЕРЕД значением не препятствуют («2026 2,2»,
    «Таблица 3. 2,2%»). Для сгруппированной формы дополнительно блокируется стык с соседней
    группой цифр через пробел («1 12 345» не подтверждает 12345): пробел внутри группировки —
    часть числа, а не межсловный промежуток."""
    before_glue = any(
        (
            start > 0 and text[start - 1].isdigit(),
            start > 1 and text[start - 1] in _DECIMAL_SEPARATORS and text[start - 2].isdigit(),
            glued_space and start > 1 and text[start - 1] == " " and text[start - 2].isdigit(),
        )
    )
    after_glue = any(
        (
            end < len(text) and text[end].isdigit(),
            end + 1 < len(text) and text[end] in _DECIMAL_SEPARATORS and text[end + 1].isdigit(),
            glued_space and end + 1 < len(text) and text[end] == " " and text[end + 1].isdigit(),
        )
    )
    return not (before_glue or after_glue)


def claim_values_found_in_texts(
    *, values: frozenset[str], texts: Iterable[str | None]
) -> frozenset[str]:
    """T7.108 (часть а, ADR-0034 §10; правка границ T7.108a): какие значения утверждения
    встречаются в текстах улики.

    Сторона утверждения не изменена: набор значений даёт `claim_value_numbers` (тот же
    `_canonical_number`, что у детекторов). Сторона ТЕКСТА (T7.108a): значение найдено, если в
    тексте есть его ТЕКСТОВАЯ ФОРМА (`_value_text_forms`: десятичный разделитель «.» или «,»,
    допустимые хвостовые нули дробной части — 2,2 ≡ 2,20; целые и сгруппированные значения —
    группы по три цифры через пробел, «1 649» ≡ «1649»), перед которой не стоит цифра и не
    стоит пара «цифра + разделитель», и после которой не стоит цифра и не стоит пара
    «разделитель + цифра» (`_form_is_standalone`). Пробел, табуляция, перевод строки и точка
    с пробелом перед значением не препятствуют: табличные строки первоисточников («2026 2,3 2,2»,
    «Таблица 3. 2,2%») подтверждают значение — прежде жадный токен склеивал соседние ячейки
    в одно число и гейт снимал законные связи именно с первичных страниц. Число внутри другого
    числа («122,2» против «2,2») и граничные числа страницы (размер файла «52.22 Кб», объём
    «12,2 Мб», годы выпуска) подтверждением не считаются — их блокируют границы формы.
    Соседние ячейки больше не склеиваются: «12 2,2» находит 2,2 как вторую ячейку — это допустимо
    (группировка разрядов идёт тройками, «12 2,2» не может быть числом 122,2; ADR-0034 §10).
    Со стороны ТЕКСТА единица измерения не требуется — табличная страница пишет «2.2» без «%».
    Бюджет сканирования общий с детектором страниц: `MAX_SCAN_CHARS` (тот же
    `RESEARCH_CONTEXT_BUDGET`); сохранённый текст страницы длиннее бюджета всё равно не существует.
    """
    if not values:
        return frozenset()
    forms = {value: _value_text_forms(value) for value in values}
    found: set[str] = set()
    for text in texts:
        if not text:
            continue
        scanned = normalize_scan_text(text)[:MAX_SCAN_CHARS]
        for value, value_forms in forms.items():
            if value in found:
                continue
            for form in value_forms:
                glued_space = " " in form
                start = scanned.find(form)
                while start != -1:
                    if _form_is_standalone(scanned, start, start + len(form), glued_space=glued_space):
                        found.add(value)
                        break
                    start = scanned.find(form, start + 1)
    return frozenset(found)


def claim_ranges_found_in_texts(
    *, ranges: frozenset[str], texts: Iterable[str | None]
) -> frozenset[str]:
    """T7.113 (часть 2, ADR-0034 §10): подтверждены ли ДИАПАЗОННЫЕ значения утверждения на
    текстах улики — только в двух формах, одиночный конец диапазона связью не подтверждается.

    Диапазон утверждения (`claim_match_values`, составной токен `2.1-2.2`) подтверждён, если:
    (1) во фрагменте или полном тексте страницы диапазон стоит КАК ОДНО ЗНАЧЕНИЕ — тот же
        читатель диапазонов T7.109a (`_range_value_spans`: соединители `_RANGE_CONNECTOR`,
        единица после правого конца) и та же эквивалентность `_canonical_number` («2,1–2,2%»,
        «2.1-2.2%», «от 2,1 до 2,2%» — одно и то же `2.1-2.2`); или
    (2) оба конца диапазона стоят ОТДЕЛЬНЫМИ числами (те же текстовые формы и границы
        `claim_values_found_in_texts`/`_form_is_standalone`, единица со стороны текста не
        требуется): таблица «мин./макс.» с отдельными ячейками «2,1» и «2,2» подтверждает
        диапазон целиком — на этой форме стендовая связка 4e7ba8c2↔finmarket и держалась бы
        честно, если бы страница несла оба конца.
    Одна граница диапазона («2,2%» при утверждении «2,1–2,2%») подтверждением не считается:
    страница подтверждает только половину утверждения — связка снимается с прежней причиной
    гейта (T7.108). Одиночные значения утверждения читает прежний
    `claim_values_found_in_texts` — его поведение не изменено ни на пункт."""
    if not ranges:
        return frozenset()
    scanned_texts = [normalize_scan_text(item)[:MAX_SCAN_CHARS] for item in texts if item]
    confirmed: set[str] = set()
    for token in ranges:
        left, sep, right = token.partition(_RANGE_TOKEN_SEP)
        if not sep or not left or not right:
            continue  # токен не читается как диапазон — подтверждать нечего
        whole = any(
            token in {span_token for _start, _end, span_token in _range_value_spans(scanned)}
            for scanned in scanned_texts
        )
        if whole:
            confirmed.add(token)  # (1) диапазон как одно измеренное значение
            continue
        ends = claim_values_found_in_texts(
            values=frozenset({left, right}), texts=scanned_texts
        )
        if left in ends and right in ends:
            confirmed.add(token)  # (2) оба конца отдельными числами (ячейки таблицы «мин./макс.»)
    return frozenset(confirmed)


def claim_range_tokens(match_values: frozenset[str]) -> frozenset[str]:
    """T7.113 (часть 2): какие из значений сравнения `claim_match_values` — составные токены
    диапазонов (`2.1-2.2`). Одиночные значения канонического формата (`цифры.цифры`) дефис не
    содержат: разбиение полное, остаток — одиночные значения утверждения."""
    return frozenset(value for value in match_values if _RANGE_TOKEN_SEP in value)


def _measured_value_spans(text: str, match_values: frozenset[str]) -> list[tuple[int, int]]:
    """Позиции в тексте каждого значения утверждения (то же сравнение, что и
    `_measured_value_tokens`, T7.109a: одиночные измеренные числа и диапазоны целиком): окно
    публикации привязывается к месту, где значение стоит на странице (для диапазона — к его
    левому концу)."""
    ranges = _range_value_spans(text)
    spans = [(start, end) for start, end, token in ranges if token in match_values]
    covered = {(start, end) for start, end, _token in ranges}
    spans.extend(
        (match.start(), match.end())
        for match in VALUE_NUMBER_PATTERN.finditer(text)
        if _UNIT_SCAN.match(text[match.end() : match.end() + _UNIT_TAIL_CHARS])
        and not any(
            start <= match.start() and match.end() <= end for start, end in covered
        )  # конец диапазона: не самостоятельная позиция значения (T7.109a)
        and _canonical_number(match.group()) in match_values
    )
    return spans


def _own_assessment_veto(
    *, scanned: str, masked: str, match_values: frozenset[str]
) -> bool:
    """T7.113 (часть а, ADR-0029 дополнение): вето собственной оценки — окрестность значения.

    Утверждение с измеренными значениями (`claim_match_values`): маркеры собственной оценки
    (по копии скан-текста с вырезанными плашками площадки T7.107) ветоют только тогда, когда их
    интервал пересекает окрестность хотя бы одного вхождения значения утверждения на странице:
    `OWN_ASSESSMENT_PROXIMITY_CHARS` знаков в обе стороны от позиции вхождения
    (`_measured_value_spans` — одиночное число или составной диапазон целиком; маска плашек
    сохраняет длину текста, координаты вхождений стоят по тому же скан-тексту). Маркер вне
    окрестностей всех вхождений вето не даёт: плашка боковой колонки и заголовок чужой новости не
    отвечают на вопрос «чьё это число» (ADR-0029 «Риски», STATUS T7.113). Настоящая оценка рядом
    с числом («по нашим расчётам … 2,2%») ветоет по-прежнему.

    Утверждение без измеренного значения: вето по всему основанию, как прежде (окрестностей нет,
    проверять «рядом с чем» нечего — поведение T7.78…T7.107 сохранено целиком). Значение есть у
    утверждения, но его нет на странице: вето молчит — отказ назовёт pairing (значения на
    странице нет ни в одной атрибуции), а не туманная «собственная оценка» страницы.
    """
    if not match_values:
        return any(pattern.search(masked) for pattern in _OWN_ASSESSMENT)
    spans = _measured_value_spans(scanned, match_values)
    if not spans:
        return False
    return any(
        match.start() < end + OWN_ASSESSMENT_PROXIMITY_CHARS
        and match.end() > start - OWN_ASSESSMENT_PROXIMITY_CHARS
        for pattern in _OWN_ASSESSMENT
        for match in pattern.finditer(masked)
        for start, end in spans
    )


def _measured_spans(text: str) -> list[tuple[int, int, frozenset[str]]]:
    """Измеренные значения текста с их позициями и токенами сравнения: (start, end, {значение}).
    Тот же измеритель, что у `_measured_numbers` (единица рядом с числом), — позиция добавлена
    для режима «ближайший первоисточник» (T7.109): там важно не только «какие числа есть»,
    но и «какое из них ближайшее после алиаса». С T7.109a диапазон — один интервал от левого
    конца до правого с составным токеном: его концы отдельными интервалами не становятся."""
    spans: list[tuple[int, int, frozenset[str]]] = []
    ranges = _range_value_spans(text)
    spans.extend((start, end, frozenset({token})) for start, end, token in ranges)
    for match in VALUE_NUMBER_PATTERN.finditer(text):
        tail = text[match.end() : match.end() + _UNIT_TAIL_CHARS]
        if not _UNIT_SCAN.match(tail):
            continue
        if any(start <= match.start() and match.end() <= end for start, end, _token in ranges):
            continue  # конец диапазона: не самостоятельный замер (T7.109a)
        spans.append((match.start(), match.end(), frozenset({_canonical_number(match.group())})))
    return spans


def _publication_window(text: str, start: int, end: int) -> tuple[str, int]:
    """Окно второго режима вокруг значения: не дальше `PUBLICATION_WINDOW_CHARS` назад от числа,
    не дальше `PUBLICATION_TAIL_CHARS` вперёд, и не за границу блока (одиночный перевод строки —
    граница блока вёрстки нормализованного текста). Возвращает окно и его начало в тексте: зоны
    вето считаются в координатах окна, а позиции значений — в координатах документа."""
    lower = max(0, start - PUBLICATION_WINDOW_CHARS)
    break_before = text.rfind(_BLOCK_BREAK, 0, start)
    if break_before >= lower:
        lower = break_before + 1
    upper = min(len(text), end + _PUBLICATION_TAIL_CHARS)
    break_after = text.find(_BLOCK_BREAK, end)
    if 0 <= break_after < upper:
        upper = break_after
    return text[lower:upper], lower


def _is_dictionary_alias_name(name: str) -> bool:
    """Имя (из кавычек или после «опрос/исследование») опознаётся словарём первоисточников."""
    stripped = name.strip().lower()
    if not stripped:
        return False  # пустое нутро кавычек от замазанного алиаса — не другое имя
    return any(
        any(pattern.search(stripped) for pattern in patterns) for _key, (_spec, patterns) in _ALIASES.items()
    )


def _is_indicator_or_geography(name: str) -> bool:
    """Имя из белого списка обозначений показателей/единиц и географии — не действующее лицо."""
    return name.upper() in INDICATOR_AND_GEOGRAPHY_ABBREVIATIONS


def _abbreviation_sign(masked: str) -> bool:
    """T7.85b (а): сокращённое имя организации вне словаря первоисточников. Алиасы словаря уже
    замазаны, поэтому «ЦБ», «Росстат» и «ФНС» сюда не приходят; остаётся чужое сокращённое имя —
    ВЦИОМ, ФОМ, РАНХиГС, ЦМАКП, НИУ ВШЭ. Имена показателей и география (ИПЦ, ВВП, CPI, РФ, США)
    — не действующие лица (см. `INDICATOR_AND_GEOGRAPHY_ABBREVIATIONS`)."""
    for match in OTHER_SOURCE_ABBREVIATION_TOKEN.finditer(masked):
        token = match.group()
        if sum(1 for char in token if char.isupper()) < 2:
            continue  # одна заглавная буква: начало предложения или обычное слово — не аббревиатура
        if _is_indicator_or_geography(token):
            continue
        return True
    return False


def _latin_proper_name_sign(masked: str) -> bool:
    """T7.85c (в): латинское имя собственное вне словаря первоисточников в русской зоне вето.
    Алиасы словаря уже замазаны, поэтому «Rosstat», «Bank of Russia» и «cbr.ru» сюда не приходят;
    остаётся чужое имя — Gallup, Reuters, Bloomberg, SberCIB. Имена показателей и география
    (HICP, CPI, EU) — не действующие лица (см. `INDICATOR_AND_GEOGRAPHY_ABBREVIATIONS`)."""
    for match in OTHER_SOURCE_LATIN_PROPER_NAME_TOKEN.finditer(masked):
        token = match.group()
        if _is_indicator_or_geography(token):
            continue
        return True
    return False


def _fixation_verb_sign(masked: str) -> bool:
    """T7.85b (б): глагол фиксации/измерения ЧУЖОГО действующего лица. Глагол сам по себе не
    признак — измерения публикуют и первоисточники; признаком он становится только вплотную к
    незамазанному имени собственному («ВЦИОМ зафиксировал», «зафиксировала ФОМ», «показали
    Левада-Центр»). Имена белого списка (показатель, география) актёрами не считаются."""
    for pattern in (_SUBJECT_THEN_VERB, _VERB_THEN_SUBJECT):
        for match in pattern.finditer(masked):
            if match.group("subject") is None:
                continue
            if _is_indicator_or_geography(match.group("subject")):
                continue  # «ИПЦ зафиксировал рост» — имя показателя, а не действующее лицо
            return True
    return False


def _other_source_sign(zone: str) -> bool:
    """Есть ли в зоне (от конца фразы атрибуции публикации до числа включительно с его
    предложением) хоть один признак ДРУГОГО источника этого числа: действующее лицо, глагол или
    оборот оценки/прогноза, название в кавычках вне словаря, «опрос/исследование» с чужим
    заказчиком, сокращённое имя организации вне словаря или глагол фиксации/измерения, совершённый
    не первоисточником (T7.85b), либо латинское имя собственное вне словаря (T7.85c). Любой
    признак — сомнение → приписывание запрещено."""
    masked = _mask_primary_aliases(zone)
    for pattern in OTHER_SOURCE_ACTOR_MARKERS:
        if re.search(pattern, masked, re.IGNORECASE):
            return True
    for pattern in OTHER_SOURCE_ESTIMATION_MARKERS:
        if re.search(pattern, masked, re.IGNORECASE):
            return True
    for match in _QUOTED_NAME.finditer(masked):
        quoted = (match.group(1) if match.group(1) is not None else match.group(2)) or ""
        quoted = quoted.strip()
        if not quoted:
            continue  # в кавычках был алиас словаря (нутро замазано) — это не другое имя
        if not _is_dictionary_alias_name(quoted):
            return True  # название в кавычках вне словаря: например «инФОМ» вне фразы атрибуции
    for survey_pattern in _SURVEY_CUSTOMER:
        for survey_match in survey_pattern.finditer(masked):
            if not _is_dictionary_alias_name(survey_match.group("customer")):
                return True  # «Исследование Ромир показало 14,5%» — чужой заказчик
    # T7.85b: «ВЦИОМ зафиксировал… 15,2%» — сокращённое имя организации вне словаря; глагол
    # фиксации/измерения как действие другого лица («ФОМ насчитал…», «замеры НИУ ВШЭ показали…»)
    # T7.85c: «… ожидания стабильны. Gallup reported observed inflation of 15,2%» — латинское
    # имя организации вне словаря в русском тексте (после замазывания алиасов «Rosstat» и
    # «Bank of Russia» токеном не становится только ЧУЖОЕ имя)
    return (
        _abbreviation_sign(masked)
        or _fixation_verb_sign(masked)
        or _latin_proper_name_sign(masked)
    )


def _attribution_regions(text: str) -> list[tuple[str, int, int]]:
    """Позиции пар «шаблон атрибуции + алиас первоисточника» в окне: то же условие pairing,
    что у `_attributed_keys` (зазор не больше `ATTRIBUTION_WINDOW_CHARS`, измеренное число и
    маркер измерения в тексте), но с сохранением позиций — вето должно знать, ГДЕ кончается
    фраза атрибуции. Тот же словарь алиасов и та же дистанция: второе мнение о первоисточнике
    здесь не заводится, отличается только представление (ключ → ключ+координаты)."""
    if not any(pattern.search(text) for pattern in _TEMPLATES):
        return []
    if not VALUE_NUMBER_PATTERN.search(text):
        return []
    if not any(pattern.search(text) for pattern in _MEASUREMENTS):
        return []
    regions: set[tuple[str, int, int]] = set()
    for key, (_spec, patterns) in _ALIASES.items():
        for alias in patterns:
            for alias_match in alias.finditer(text):
                for template in _TEMPLATES:
                    for template_match in template.finditer(text):
                        near = max(
                            template_match.start() - alias_match.end(),
                            alias_match.start() - template_match.end(),
                            0,
                        )
                        if near <= ATTRIBUTION_WINDOW_CHARS:
                            regions.add(
                                (
                                    key,
                                    min(alias_match.start(), template_match.start()),
                                    max(alias_match.end(), template_match.end()),
                                )
                            )
    # детерминированный порядок: по концу фразы (нужен для выбора ближайшей к числу фразы)
    return sorted(regions, key=lambda region: (region[2], region[1], region[0]))


def _sentence_end(text: str, position: int) -> int:
    """Конец предложения, в котором стоит `position` (включая терминальную пунктуацию):
    первое граница-предложение, заканчивающаяся после позиции."""
    for match in _SENTENCE_BREAK.finditer(text):
        if match.end() > position:
            return match.end()
    return len(text)


def _veto_zones(
    window: str, regions: list[tuple[int, int]], value_start: int, value_end: int
) -> list[str]:
    """Зоны вето для одного первоисточника окна (координаты — относительные окна): текст от
    конца каждой фразы атрибуции публикации, закончившейся ДО числа, до конца предложения с
    числом включительно. Проверяются ВСЕ такие фразы: ближайшая к числу «ведёт» это значение,
    но и более ранняя фраза того же первоисточника не имеет права пропускать смену источника
    по дороге к числу. Отдельный случай — пары, начинающиеся у числа или после него («…составила
    14,5%, как сообщил ЦБ»): их зона — остаток собственного предложения. Композитные пары, где
    шаблон атрибуции стоит ближе к чужому обороту («По оценке ВШЭ … Банк России»), тоже дают
    зоны: сама такая склейка подозрительна, а её остаток к числу проверяется на признаки."""
    zones: list[str] = []
    zone_end = _sentence_end(window, value_end)
    preceding = [region for region in regions if region[1] <= value_start]
    if preceding:
        for _region_start, region_end in preceding:
            zones.append(window[region_end:zone_end])
        return zones
    for _region_start, region_end in regions:
        if region_end > value_start:
            zones.append(window[region_end : _sentence_end(window, max(region_end, value_end))])
    return zones


# ─── T7.107 (ADR-0029 дополнение): третий режим pairing — список источников + известный производитель ──
#
# Стендовый дефект (утверждение 7cfbe942 «безработица 2,2% по данным Росстата», страница
# smart-lab.ru/blog/1349924.php): блог пересказывает официальную цифру и честно перечисляет
# источники внизу страницы («Источники: Росстат, обзор рынка труда hh.ru …, материалы Банка
# России, …»), но ни строгий режим (пары «шаблон+алиас+значение» в теле нет), ни режим публикации
# (публикация первоисточника не объявлена) не могли это увидеть, а вето сработало по плашке
# площадки. Другая улика того же утверждения (interfax.ru/business/1119461) уже приписана
# Росстату строгим режимом — знание о производителе утверждения УЖЕ ЕСТЬ у самого утверждения,
# и его достаточно, чтобы прочесть строку-список как атрибуцию, не изобретая новый признак
# «первоисточник на любой странице».
#
# Условия (все одновременно, fail-closed; ADR-0029 «Риски»: ложная склейка дороже пропуска):
# (i)  на странице есть строка-список источников — строка нормализованного текста, начинающаяся
#      с маркера ЗАКРЫТОГО списка `BIBLIOGRAPHY_LINE_MARKERS`, и в ЭТОЙ строке стоит словарный
#      алиас производителя X;
# (ii) число значения утверждения присутствует на странице как ИЗМЕРЕННОЕ число (тот же помощник
#      `_measured_numbers`, что у режима публикации: «2026» годом не считается);
# (iii) у ЭТОГО ЖЕ утверждения есть ДРУГАЯ улика, записанная pairing строгого режима или режима
#      публикации, с primary_key = X; функция остаётся чистой — множество таких ключей передаёт
#      вызывающий (`known_claim_primaries`), сами вызывающие его и собирают (`reattribution.py`,
#      оркестратор). Цепочек нет: записью нового режима ключ не пополняется (собирающие читают
#      pairing строгого режима и режима публикации);
# (iv) ровно один известный производитель назван в строках-списках; два известных названы оба —
#      отказ `ambiguous_primaries`; ни одного названного — честный отказ (не own_assessment);
# (v)  вето собственной оценки (после маски плашек T7.107) на странице не сработало, и страница
#      НЕ домашняя для X (первоисточник не пересказывает себя).
#: маркеры начала строки-списка источников (закрытый список). «По данным:» и подобные шаблоны
#: атрибуции сюда НЕ входят: они уже принадлежат строгому режиму.
BIBLIOGRAPHY_LINE_MARKERS: Final[tuple[str, ...]] = (
    "источник:",
    "источники:",
    "источники данных:",
    "по материалам:",
    "source:",
    "sources:",
)
_BIBLIOGRAPHY_LINE: Final = re.compile(
    r"^[ \t]*(?:" + "|".join(re.escape(marker) for marker in BIBLIOGRAPHY_LINE_MARKERS) + ")",
    re.IGNORECASE,
)


def _bibliography_lines(scanned: str) -> list[str]:
    """Строки нормализованного текста, начинающиеся с маркера закрытого списка (T7.107)."""
    return [line for line in scanned.split("\n") if _BIBLIOGRAPHY_LINE.match(line)]


def _bibliography_known_producer_decision(
    *,
    scanned_page: str,
    canonical_uri: str | None,
    values: tuple[str, ...],
    known_claim_primaries: frozenset[str],
    match_values: frozenset[str],
) -> ValueAttributionDecision | None:
    """Третий, последний режим pairing (T7.107): кому принадлежит значение утверждения, когда
    страница назвала список источников, а производителя уже назвала другая улика того же
    утверждения. None — честный отказ (условие не собрано); решение `ambiguous_primaries` —
    два известных производителя названы. Родительский указатель разрешает вызывающий, как у
    строгого режима."""
    if not known_claim_primaries or not values:
        return None  # известного производителя нет — новый режим нечем подтвердить (отказ)
    if _own_assessment_veto(
        scanned=scanned_page,
        masked=_mask_site_disclaimers(scanned_page),
        match_values=match_values,
    ):
        return None  # (v) настоящая собственная оценка рядом со значением утверждения на
        # странице — склейки не будет (T7.113 часть а: тот же критерий окрестности, что у
        # строгой ветки; плашки площадки T7.107 замазаны, словарь маркеров не сокращён)
    lines = _bibliography_lines(scanned_page)
    if not lines:
        return None  # (i) строки-списка нет
    if not (match_values and (_measured_value_tokens(scanned_page) & match_values)):
        return None  # (ii) значения утверждения на странице нет (T7.109a: диапазон — значение
        # целиком, его концы одиночным числом утверждения не подтверждают)
    named_known = [
        (key, line)
        for line in lines
        for key in set(named_primary_keys(line)) & known_claim_primaries
    ]
    distinct_keys = {key for key, _line in named_known}
    if len(distinct_keys) > 1:
        # (iv) два известных производителя названы в списках — разночтение, не склеиваем
        basis_line = next(line for key, line in named_known if key in distinct_keys)
        return ValueAttributionDecision(
            status=STATUS_AMBIGUOUS,
            basis_fragment=_basis(basis_line),
            claim_values=values,
            pairing=PAIRING_BIBLIOGRAPHY_KNOWN_PRODUCER,
        )
    if not named_known:
        return None  # (iv) известный производитель в списке не назван — честный отказ
    key = next(iter(distinct_keys))
    spec = primary_source(key)
    if spec is None:  # защита: решение не строится на несуществующей записи словаря
        return None
    if is_home_host(canonical_uri, spec.home_hosts):
        return None  # (v) страница самого X не бывает его пересказом
    _named_key, basis_line = named_known[0]
    return ValueAttributionDecision(
        status=STATUS_DERIVATIVE,
        primary_key=spec.key,
        primary_name=spec.name,
        parent_uri=spec.home_uri,
        basis_fragment=_basis(basis_line),
        claim_values=values,
        pairing=PAIRING_BIBLIOGRAPHY_KNOWN_PRODUCER,
    )


def _publication_decision(
    *,
    scanned: str,
    canonical_uri: str | None,
    values: tuple[str, ...],
    match_values: frozenset[str],
) -> ValueAttributionDecision | None:
    """Второй режим pairing (T7.85): страница объявила публикацию первоисточника в предыдущих
    предложениях того же блока, а значение называет позже.

    Условия строже строгого режима по всем остальным пунктам: то же окно «шаблон + алиас»
    (`ATTRIBUTION_WINDOW_CHARS`), то же требование измеренного числа и маркера измерения, то же
    правило «страница первоисточника не бывает его пересказом», тот же отказ при разночтении.
    Дополнительно: в окне обязано быть название публикации первоисточника (`PUBLICATION_MARKERS`),
    и если в одном окне назван хоть один второй первоисточник — решение не принимается вовсе.

    T7.85a добавляет вето «другого источника числа» (`_other_source_sign`): если между концом
    фразы атрибуции публикации и числом — включительно с его предложением — стоит другое
    действующее лицо, глагол или оборот оценки/прогноза, название в кавычках вне словаря или
    «опрос/исследование» с чужим заказчиком, первоисточник не допускается кандидатом на это
    значение. Вето только снимает кандидатов и никогда их не добавляет: разночтение окон
    остаётся отказом даже там, где один из кандидатов был затронут вето.

    T7.85b расширяет тот же список двумя признаками того же направления: сокращённое имя
    организации вне словаря первоисточников (`_abbreviation_sign`: «ВЦИОМ зафиксировал… 15,2%») и
    глагол фиксации/измерения как действие другого лица (`_fixation_verb_sign`: «ФОМ насчитал…»,
    «замеры НИУ ВШЭ показали…»). Оба проверяются после замазывания алиасов словаря и с белым
    списком обозначений показателей/географии, поэтому «Росстат показал…» и «Банк России
    зафиксировал оценку…» остаются пересказом первоисточника.

    T7.85c сужает сам режим: маркеры публикации (`PUBLICATION_MARKERS`) — русские, то есть окно
    работает только там, где его собственное вето действительно действует (признаки вето — русские
    списки, чужой язык они не охраняют). И расширяет тот же список одним признаком: латинским
    именем собственным вне словаря (`_latin_proper_name_sign`: «…ожидания стабильны. Gallup
    reported observed inflation of 15,2%»). Строгий режим не тронут: английская пара
    «значение + первоисточник» в одном фрагменте решалась по нему и раньше."""
    if not match_values:
        return None  # значения нет: расширять pairing нечем (строгий режим строже)
    candidates_all: dict[str, str] = {}  # кандидаты до вето — прежнее поведение режима (T7.85)
    candidates: dict[str, str] = {}  # кандидаты, пережившие вето «другого источника числа» (T7.85a)
    ambiguity_basis: str | None = None
    for start, end in _measured_value_spans(scanned, match_values):
        window, window_lower = _publication_window(scanned, start, end)
        if not any(pattern.search(window) for pattern in _PUBLICATIONS):
            continue  # публикация первоисточника не названа: окно не расширяем
        attributed = _attributed_keys(window)
        if not attributed:
            continue
        named = set(named_primary_keys(window))
        if len(named) > 1:
            # в одном окне с значением названы два разных первоисточника — разночтение
            ambiguity_basis = window
            continue
        regions_of_key: dict[str, list[tuple[int, int]]] = {}
        for key, region_start, region_end in _attribution_regions(window):
            if key in attributed:
                regions_of_key.setdefault(key, []).append((region_start, region_end))
        for key, basis in attributed.items():
            if is_home_host(canonical_uri, _home_hosts(key)):
                continue  # страница первоисточника не бывает его пересказом (то же правило)
            candidates_all[key] = basis
            zones = _veto_zones(
                window, regions_of_key.get(key, []), start - window_lower, end - window_lower
            )
            if not any(_other_source_sign(zone) for zone in zones):
                candidates[key] = basis
    if ambiguity_basis is not None:
        return ValueAttributionDecision(
            status=STATUS_AMBIGUOUS,
            basis_fragment=_basis(ambiguity_basis),
            claim_values=values,
            pairing=PAIRING_PUBLICATION_WINDOW,
        )
    if not candidates_all:
        return None
    if len(candidates_all) > 1:
        # разночтение окон остаётся отказом независимо от вето (вето не улучшает решение)
        return ValueAttributionDecision(
            status=STATUS_AMBIGUOUS,
            basis_fragment=_basis(next(iter(candidates_all.values()))),
            claim_values=values,
            pairing=PAIRING_PUBLICATION_WINDOW,
        )
    key = next(iter(candidates_all))
    if key not in candidates:
        return None  # вето сняло единственного первоисточника на всех его occurrences: сомнение — не приписывать
    spec = primary_source(key)
    if spec is None:  # защита: решение не строится на несуществующей записи словаря
        return None
    return ValueAttributionDecision(
        status=STATUS_DERIVATIVE,
        primary_key=spec.key,
        primary_name=spec.name,
        parent_uri=spec.home_uri,
        basis_fragment=_basis(candidates[key]),
        claim_values=values,
        pairing=PAIRING_PUBLICATION_WINDOW,
    )


def _nearest_primary_keys(fragment: str, match_values: frozenset[str]) -> dict[str, str]:
    """T7.109 (часть б2, решение пользователя 2026-10-13) «ближайший первоисточник»: кому
    принадлежит значение во фрагменте, называющем ДВУХ и более словарных первоисточников.

    Именно там молчит гвард (а) relay («два первоисточника названы — чей прогноз, неизвестно»);
    во фрагментах с одним алиасом прежние режимы решают как решали, этот код к ним не
    прикасается. Вето третьего актора — то же, что у гварда (б) relay (`_third_actor_present`:
    поиск по фону замазанных алиасов словаря): «прогноз ЦБ (6-7%) и прогноз Минэкономразвития
    (6,8%), по оценке аналитиков...» не решает ничего.

    Правило близости: значение приписывается алиасу, который стоит ближе всего перед значением,
    — собственное измеренное число алиаса, ближайшее после его вхождения, обязано нести значение
    утверждения. Если ближайшее число другое, это вхождение алиаса значение не заявляет («ЦБ
    сохранил ставку 14%. Прогноз инфляции ЦБ — 6-7%»: 6–7 принадлежит ЦБ по второму вхождению,
    а 14 к значению 6–7 не относится). Между алиасом и его числом не может стоять другое
    измеренное число — оно и будет ближайшим собственным числом алиаса.

    Вето home-host и разночтение двух претендентов решает вызывающий код (тот же, что у relay и
    шаблонных пар): эта функция называет кандидатов фрагмента, не больше."""
    if not match_values:
        return {}
    keys = named_primary_keys(fragment)
    if len(keys) < 2:
        return {}  # одиночный алиас: гвард (а) relay и прежние режимы уже отработали
    if _third_actor_present(fragment):
        return {}  # фрагмент называет третье действующее лицо — как гвард (б) relay
    spans = _measured_spans(fragment)
    if not spans:
        return {}
    candidates: dict[str, str] = {}
    for key in keys:
        for pattern in _ALIASES[key][1]:
            claimed = False
            for occurrence in pattern.finditer(fragment):
                following = min(
                    (span for span in spans if span[0] >= occurrence.end()),
                    key=lambda span: span[0],
                    default=None,
                )
                if following is not None and following[2] & match_values:
                    candidates[key] = fragment
                    claimed = True
                    break
            if claimed:
                break
    return candidates


def _nearest_primary_decision(
    *,
    scanned: str,
    canonical_uri: str | None,
    values: tuple[str, ...],
    match_values: frozenset[str],
) -> ValueAttributionDecision | None:
    """Решение режима «ближайший первоисточник» (T7.109) либо None — режима нет, когда ни один
    фрагмент не называет двух словарных первоисточников, заявляющих значение утверждения.

    Pairing решения — прежний строгий `value_and_primary_in_fragment` (значение и первоисточник
    в одном фрагменте, связь выражена близостью алиаса к значению): новых pairing-значений и
    новых ключей evidence scope нет. Home-host правило то же: страница не бывает пересказом
    самой себе, и если все претенденты — домашние для прочитанной страницы, режим молчит
    (собственную публикацию утверждает не этот режим, а `self_primary`). Два претендента —
    прежнее `ambiguous_primaries`; кандидата нет — прежний честный отказ вызывающего кода."""
    if not match_values:
        return None
    candidates_all: dict[str, str] = {}
    for fragment in _fragments(scanned):
        for key, basis in _nearest_primary_keys(fragment, match_values).items():
            candidates_all.setdefault(key, basis)
    if not candidates_all:
        return None
    candidates = {
        key: basis
        for key, basis in candidates_all.items()
        if not is_home_host(canonical_uri, _home_hosts(key))
    }
    if not candidates:
        return None  # значение заявлено самой прочитанной страницей: режим не решает
    if len(candidates) > 1:
        return ValueAttributionDecision(
            status=STATUS_AMBIGUOUS,
            basis_fragment=_basis(next(iter(candidates.values()))),
            claim_values=values,
        )
    key = next(iter(candidates))
    spec = primary_source(key)
    if spec is None:  # защита: решение не строится на несуществующей записи словаря
        return None
    return ValueAttributionDecision(
        status=STATUS_DERIVATIVE,
        primary_key=spec.key,
        primary_name=spec.name,
        parent_uri=spec.home_uri,
        basis_fragment=_basis(candidates[key]),
        claim_values=values,
    )


def _pairing_maps(
    scanned: str, values: tuple[str, ...], match_values: frozenset[str]
) -> tuple[dict[str, str], dict[str, str]]:
    """Пары фрагментов: `attributed` — фрагменты, где названа атрибуция (независимо от значения),
    `matched` — пары «первоисточник → фрагмент» про значение утверждения. Вынесено из
    `attribute_value_in_fragment` дословно (T7.101): решение о собственной публикации обязано
    строиться на ровно том же pairing, что и решение об атрибуции, — второй копии логики нет.
    С T7.109a фильтр «другого числа» сравнивает значения фрагмента с профилем утверждения
    (`_measured_value_tokens`: диапазон страницы — одно значение, его концы — не числа):
    фрагмент с единственным диапазоном «6-7%» больше не пропускает одиночное значение «7»."""
    attributed: dict[str, str] = {}
    matched: dict[str, str] = {}
    for fragment in _fragments(scanned):
        keys = _attributed_keys(fragment)
        # T7.98: relay-кандидат строгого режима — прогноз первоисточника без шаблона.
        # Он не ослабляет шаблонную пару: тот же фрагмент, то же окно, то же вето; при
        # разногласии шаблона и relay в одном фрагменте разночтение решает тот же код ниже.
        # Relay различает два вопроса (гвард (е)): «первоисточник назван субъектом прогноза»
        # (атрибуция основания) и «значение утверждения стоит на позиции значения прогноза»
        # (атрибуция значения): «составила 5,59%, оказавшись ниже прогноза Банка России 6–7%»
        # называет ЦБ в основании, но 5,59 ЦБ не принадлежит → value_not_attributed, а не
        # ложный пересказ. С T7.109a требуемые числа relay остаются плоскими (позиции значений
        # прогноза в тексте не меняются), но одиночное значение до relay-проверки не доходит:
        # диапазон отсекается фильтром профиля раньше.
        relay = _relay_forecast_keys(fragment)
        if not keys and not relay:
            continue
        attributed.update(dict.fromkeys({**relay, **keys}, fragment))
        if match_values and not (_measured_value_tokens(fragment) & match_values):
            continue  # «другое число»: первоисточник назван, но не про значение утверждения (T7.109a)
        relay_value = (
            _relay_forecast_keys(fragment, required_numbers=frozenset(values))
            if relay and values
            else relay
        )
        matched.update(dict.fromkeys({**relay_value, **keys}, fragment))
    return attributed, matched


def attribute_value_in_fragment(
    *,
    canonical_uri: str | None,
    text: str | None,
    claim_statement: str | None = None,
    known_claim_primaries: frozenset[str] = frozenset(),
    page_text: str | None = None,
) -> ValueAttributionDecision:
    """Кому принадлежит значение, на котором стоит утверждение.

    `text` — основание улики: фрагмент прочитанной страницы (для новой улики это `assertion_text`,
    для уже существующей — весь сохранённый нормализованный текст страницы: долговременного фрагмента
    у строки улики нет, ограничение описано в STATUS T7.78). `canonical_uri` — адрес прочитанной
    страницы, `claim_statement` — формулировка утверждения (может отсутствовать).

    T7.107: `known_claim_primaries` — primary_key производности, записанные pairing строгого режима
    или режима публикации по ДРУГИМ уликам ЭТОГО ЖЕ утверждения; собирает их вызывающий
    (`reattribution.py`, оркестратор), новый режим ключи не пополняет (цепочек нет). Пустое множество
    — поведение ровно прежнее. `page_text` — весь нормализованный текст страницы, если он есть у
    вызывающего: третий режим (`bibliography_known_producer`) читает строку-список источников по нему,
    когда списка нет в основании улики; строгий режим и режим публикации решением `page_text` не
    расширяются — их основанием остаётся `text`.
    """
    if not text:
        return ValueAttributionDecision(status=STATUS_NO_VALUE_ATTRIBUTION)

    scanned = normalize_scan_text(text)[:MAX_SCAN_CHARS]
    values = claim_value_numbers(claim_statement)
    # T7.109a: профиль значений утверждения для сравнения «значение ли это в этом фрагменте»;
    # плоский `values` остаётся для записи, гейта и позиций relay
    match_values = claim_match_values(claim_statement)

    # T7.107/T7.113 (часть а): вето собственной оценки — по копии с вырезанными шаблонными
    # плашками площадки (`SITE_DISCLAIMER_PHRASES`), словарь маркеров не сокращён; когда у
    # утверждения есть измеренные значения, маркер обязан попасть в окрестность их вхождения на
    # странице (`OWN_ASSESSMENT_PROXIMITY_CHARS`), иначе вето нет — плашка боковой колонки или
    # заголовок чужой новости не отвечают на вопрос «чьё это число». Утверждение без измеренного
    # значения — прежнее вето по всему основанию.
    if _own_assessment_veto(
        scanned=scanned, masked=_mask_site_disclaimers(scanned), match_values=match_values
    ):
        # своя оценка/альтернативный расчёт рядом со значением утверждения: склеивать нельзя
        return ValueAttributionDecision(status=STATUS_OWN_ASSESSMENT, claim_values=values)

    attributed, matched = _pairing_maps(scanned, values, match_values)

    def fallback(refusal: ValueAttributionDecision) -> ValueAttributionDecision:
        """Честный отказ строгого режима ещё не значит «пересказа нет»: страница могла объявить
        публикацию первоисточника в предыдущих предложениях того же блока. Второй режим
        рассматривается ТОЛЬКО после отказа строгого — строгий режим не ослаблен ни на пункт.

        `own_assessment` и `self_primary` сюда не приходят: первое — вето на весь документ,
        второе уже утверждает, что значение принадлежит прочитанной странице (отрицательный
        контроль T7.85: собственная страница ЦБ по опросу «инФОМ» не становится пересказом).

        Третий режим T7.107 (`_bibliography_known_producer_decision`) рассматривается только после
        отказа прежних — прежние режимы не ослаблены ни на пункт. С T7.109 между ними встаёт
        режим «ближайший первоисточник» (`_nearest_primary_decision`): он тоже рассматривается
        только после честного отказа строгого и публикационного режимов и ничего в них не
        меняет; pairing его решения — строгий, новых статусов и ключей нет."""
        wider = _publication_decision(
            scanned=scanned, canonical_uri=canonical_uri, values=values, match_values=match_values
        )
        if wider is not None:
            return wider
        nearest = _nearest_primary_decision(
            scanned=scanned, canonical_uri=canonical_uri, values=values, match_values=match_values
        )
        if nearest is not None:
            return nearest
        if not known_claim_primaries:
            return refusal  # известного производителя утверждения нет — третьему режиму не на что опереться
        bibliography_page = (
            normalize_scan_text(page_text)[:MAX_SCAN_CHARS] if page_text is not None else scanned
        )
        bibliography = _bibliography_known_producer_decision(
            scanned_page=bibliography_page,
            canonical_uri=canonical_uri,
            values=values,
            known_claim_primaries=known_claim_primaries,
            match_values=match_values,
        )
        return refusal if bibliography is None else bibliography

    if not attributed:
        return fallback(
            ValueAttributionDecision(status=STATUS_NO_VALUE_ATTRIBUTION, claim_values=values)
        )

    # страница самого первоисточника не бывает его пересказом
    candidates = {
        key: basis
        for key, basis in matched.items()
        if not is_home_host(canonical_uri, _home_hosts(key))
    }
    if not candidates:
        if not matched:
            # атрибуции в основании были, но все — про другие числа утверждения
            return fallback(
                ValueAttributionDecision(status=STATUS_VALUE_NOT_ATTRIBUTED, claim_values=values)
            )
        own_only = all(is_home_host(canonical_uri, _home_hosts(key)) for key in matched)
        if own_only:
            return ValueAttributionDecision(
                # значение утверждения приписано самой прочитанной странице — она первоисточник
                status=STATUS_SELF_PRIMARY,
                claim_values=values,
            )
        return fallback(
            ValueAttributionDecision(status=STATUS_VALUE_NOT_ATTRIBUTED, claim_values=values)
        )

    if len(candidates) > 1 and match_values:
        # T7.112 (а3): новый глагол отчётности может привести строгую пару во фрагмент, называющий
        # двух словарных первоисточников сразу — прежде там молчал режим «ближайший первоисточник»
        # (строгий отказывался из-за отсутствия шаблона). Разночтение разрешается тем же принятым
        # правилом владения числом T7.109 (б2), тем же кандидатным кодом: значение заявляет тот
        # алиас, чьё ближайшее собственное число и есть значение утверждения. Это сужение
        # разночтения внутри одного фрагмента (проверка идёт по фрагменту каждого кандидата), а не
        # ослабление pairing: кандидат один — прежнее решение `derivative` того же алиаса; кандидатов
        # ноль или двое — прежний честный `ambiguous_primaries`. Разночтения между фрагментами
        # правилом не тронуты: `named_primary_keys` чужого фрагмента двух алиасов не даст.
        owners = {
            key: basis
            for key, basis in candidates.items()
            if key in _nearest_primary_keys(basis, match_values)
        }
        if owners:
            candidates = owners

    if len(candidates) > 1:
        # одному и тому же значению утверждения присвоены разные первоисточники — разночтение
        return ValueAttributionDecision(
            status=STATUS_AMBIGUOUS,
            basis_fragment=_basis(next(iter(candidates.values()))),
            claim_values=values,
        )

    key, basis = next(iter(candidates.items()))
    spec = primary_source(key)
    if spec is None:  # защита: решение не строится на несуществующей записи словаря
        return ValueAttributionDecision(status=STATUS_NO_VALUE_ATTRIBUTION, claim_values=values)
    return ValueAttributionDecision(
        status=STATUS_DERIVATIVE,
        primary_key=spec.key,
        primary_name=spec.name,
        parent_uri=spec.home_uri,
        basis_fragment=_basis(basis),
        claim_values=values,
    )


def _home_hosts(key: str) -> tuple[str, ...]:
    spec = primary_source(key)
    return () if spec is None else spec.home_hosts


# ─── T7.101 (ADR-0029 дополнение, ADR-0035 §19): решение о собственной публикации ──────────────
#
# `self_primary` существовал как честный отказ от пересказа, но ничего не сообщал витрине:
# страница Банка России с собственным прогнозом молчала «Подтверждено слабо». Решение о записи
# принимает НЕ новая детекция, а та же `attribute_value_in_fragment`: эта функция отвечает на
# второй вопрос — как зовут производителя и не чужое ли значение стоит на странице.


@dataclass(frozen=True)
class SelfPublicationCandidate:
    """Решение записать: значение утверждения на прочитанной странице — собственная публикация
    производителя на его домашнем хосте (T7.101).

    `actor_veto` — честность к ADR-0035 §15: фрагмент, давший решение, называет ТРЕТЬЕГО актора
    создателем значения («Аналитики, опрошенные…, ожидают инфляцию 6,0–7,0%» на странице ЦБ) —
    хост здесь только издатель, и запись не пишется (fail-closed: витрина молчит, как молчала)."""

    primary_key: str
    primary_name: str
    basis_fragment: str
    actor_veto: bool


def _third_actor_present(fragment: str) -> bool:
    """Есть ли во фрагменте действующее лицо — третий актор (тот же словарь, что у вето окна
    публикации и у гварда (б) relay-кандидата, T7.98): поиск по фону ЗАМАЗАННЫХ алиасов
    словаря — порядок критичен: «Банк России» в действующее лицо-банк не превращается,
    «Альфа-Банк» — превращается."""
    masked = _mask_primary_aliases(fragment)
    return any(re.search(pattern, masked, re.IGNORECASE) for pattern in OTHER_SOURCE_ACTOR_MARKERS)


def self_publication_candidate(
    *,
    canonical_uri: str | None,
    text: str | None,
    claim_statement: str | None = None,
) -> SelfPublicationCandidate | None:
    """Собственная ли публикация стоит на прочитанной странице и стоит ли её записать.

    Решение принимает `attribute_value_in_fragment` — здесь ничего не решается заново: функция
    только называет производителя по словарю и проверяет вето третьего актора. None — когда
    решение не `self_primary` (запись пишется только для этого статуса) или когда защита не
    пропускает запись: без адреса страницы, без pairing, с двумя производителями или с
    домашним хостом, не совпадающим с прочитанной страницей."""
    decision = attribute_value_in_fragment(
        canonical_uri=canonical_uri, text=text, claim_statement=claim_statement
    )
    if decision.status != STATUS_SELF_PRIMARY:
        return None
    if not canonical_uri or not text:
        return None  # защита: без адреса прочитанной страницы домашний хост не проверить
    scanned = normalize_scan_text(text)[:MAX_SCAN_CHARS]
    _, matched = _pairing_maps(scanned, decision.claim_values, claim_match_values(claim_statement))
    if not matched:
        return None  # защита: `self_primary` без pairing не бывает, но и проверка не на слепке
    specs = [
        spec
        for spec in (primary_source(key) for key in matched)
        if spec is not None and is_home_host(canonical_uri, spec.home_hosts)
    ]
    if len(specs) != 1 or {spec.key for spec in specs} != set(matched):
        return None  # запись — ровно об одном производителе, чей домашний хост мы читаем
    spec = specs[0]
    veto = any(_third_actor_present(fragment) for fragment in matched.values())
    return SelfPublicationCandidate(
        primary_key=spec.key,
        primary_name=spec.name,
        basis_fragment=_basis(matched[spec.key]),
        actor_veto=veto,
    )


def self_publication_scope_for_fragment(
    *,
    canonical_uri: str | None,
    text: str | None,
    claim_statement: str | None = None,
) -> JsonDict | None:
    """T7.104 (ADR-0035 §19 дополнение): запись о собственной публикации для НОВОЙ улики.

    Общий помощник двух путей: та же `self_publication_candidate` (те же гейты — статус
    `self_primary`, ровно один производитель, домашний хост прочитанной страницы, вето третьего
    актора) и тот же `build_self_publication` с тем же `method`, что пишет `research-reattribute
    --evidence-level` (ADR-0035 §19.2: записанное при создании фиксируется методом текущей эпохи,
    перечитывание окна её не перезаписывает — идемпотентность держится на этом же признаке).
    None — когда кандидат не пройден (ловушка Росстата T7.87, вето третьего актора, пересказ):
    запись не пишется, витрина молчит, как молчала."""
    candidate = self_publication_candidate(
        canonical_uri=canonical_uri, text=text, claim_statement=claim_statement
    )
    if candidate is None or candidate.actor_veto:
        return None
    record = build_self_publication(
        primary_key=candidate.primary_key,
        primary_name=candidate.primary_name,
        primary_uri=str(canonical_uri),
        method=VALUE_ATTRIBUTION_METHOD_VERSION,
        basis_fragment=candidate.basis_fragment,
    )
    if record is None:
        return None
    return {EVIDENCE_SELF_PUBLICATION_KEY: record.as_scope()}
