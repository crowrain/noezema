# ─── T7.85b: второе замечание приёмки — сокращённое имя оценщика и глагол фиксации ──────
# Замер на `792d2c4`/`7981f08`: «Согласно опубликованному Банком России обзору, ожидания
# стабильны. ВЦИОМ зафиксировал наблюдаемую инфляцию 15,2%» решалось как `derivative → Банк
# России`. Ни один прежний признак такого имени не видит: кавычек нет («„инФОМ“»), действующего
# лица из списка тоже нет (ВЦИОМ/ФОМ/ЦСР — не «компания» и не «центр»), а роль оценщика в тексте
# несёт только ГЛАГОЛ («зафиксировал», «насчитал», «показал»). Живой репортаж называет оценщика
# сокращённо и без кавычек именно так, поэтому окно публикации приклеивало чужое измерение к
# публикации ЦБ.

#: аббревиатура организации: токен, начинающийся с заглавной буквы и содержащий НЕ МЕНЕЕ ДВУХ
#: заглавных букв (кириллица или латиница; строчные внутри разрешены — «РАНХиГС», «ЦМАКП»,
#: «НИУ ВШЭ», «SberCIB»). Одна заглавная буква — это начало предложения или обычное существительное
#: («Инфляция», «Оценка», «России»): их проверка давала бы ложное вето на каждом втором предложении.
#: Проверка идёт по замазанной зоне, поэтому алиас словаря токеном не становится: «ЦБ РФ»,
#: «РОССТАТ» и «Банк России» к этому моменту уже пробелы (см. `_mask_primary_aliases`).
#: Сознательный риск: заголовок или служебный блок, набранный CAPS («МОНИТОРИНГ ОЖИДАНИЙ»), тоже
#: даст отказ там, где приписывание было правильным — ложное вето допустимо, ложная склейка нет.
OTHER_SOURCE_ABBREVIATION_TOKEN: Final = re.compile(r"[А-ЯЁA-Z][А-ЯЁA-Za-zа-яё]*")

#: T7.85c (в): латинское имя собственное вне словаря — слово, набранное латиницей и начинающееся
#: с заглавной буквы (длина ≥2: «Gallup», «Reuters», «Bloomberg», «SberCIB»). Русский репортаж
#: называет чужого оценщика латинским именем ровно так («…ожидания стабильны. Gallup reported
#: observed inflation of 15,2%»), и ни один прежний признак этого имени не видит: сокращённая
#: аббревиатура требует ≥2 заглавных букв (в «Gallup» одна), действующие лица и обороты оценки —
#: русские списки, имя в связке «имя␠глагол» обязано начинаться с кириллической заглавной буквы.
#: Замечание приёмки было именно про это: латинское имя организации в русском тексте действующим
#: лицом не считалось, и чужое измерение приклеивалось к публикации ЦБ.
#: Проверка, как и у аббревиатуры, идёт по ЗАМАЗАННОЙ зоне: алиас словаря латиницей
#: («Rosstat», «Bank of Russia», «cbr.ru») замазан вместе с именем и токеном не становится —
#: поэтому «Rosstat показал 5,59%» остаётся пересказом первоисточника. Имена показателей и
#: географии (`INDICATOR_AND_GEOGRAPHY_ABBREVIATIONS`) актором не считаются. Строчное начало
#: («gallup», английское обычное слово внутри русской врезки) признаком НЕ является: заглавная
#: буква — часть признака имени собственного, как и у `_NAME_SLOT`.
OTHER_SOURCE_LATIN_PROPER_NAME_TOKEN: Final = re.compile(r"[A-Z][A-Za-z]+")

