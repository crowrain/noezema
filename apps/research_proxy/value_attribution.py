#: («ИПЦ вырос на 5,59%»), а география указывает территорию значения («годовая инфляция в РФ»).
#: Вето по ним снимало бы правильные пересказы (и строгий режим, и окно), а ложную склейку они
#: создать не могут в принципе — источник склейки это публикация, а не имя показателя. География
