r"""Unit: дополнение T7.137a к каталогу названных акторов (ADR-0036 §10a).

Замер менеджера (2026-10-28): распознавание по основе слова (`_prefix_stem`) — усечение,
а усечённая основа не всегда имя. «Газпром» — основа «Газпромбанка», поэтому «Газпром нефть»
и «акции Газпрома» называли Газпромбанк; «альфа» называла Альфа-Банк в «альфа-коэффициент».
Та же усечённость ПРОПУСКАЛА имена, которые стенд правда видит: смешанную форму названия
Sber CIB, «в Сбере», единственное число «Центральный банк», «Минэк».

Проверяется:

* positives — имена, которые раньше пропускались;
* negatives — ложные попадания, которые раньше считались названными акторами, и множественное
  число («банки России», «Центральные банки»);
* закрытые шаблоны — единственный источник форм имени: витрина прогнозов (T7.138 2б) мост
  Сбербанка берёт из этой же функции, своего списка форм у неё нет;
* каталог и порядок имён в вопросе не изменились, порог гейта (`MULTI_ACTOR_MIN`) тот же;
* реплей 423 поисков фикстуры T7.137: набор отказов не изменился (красным было бы любое
  изменение порога или каталога) — см. `test_multi_actor_gate_replay_t7137.py`.
"""

from __future__ import annotations

import pytest

from apps.orchestrator.question_actors import (
    MULTI_ACTOR_MIN,
    SEPARATE_SEARCH_MAX_ACTORS,
    named_actors,
    named_query_actors,
    named_question_actors,
    names_sberbank,
)

pytestmark = pytest.mark.unit

# тот же вопрос стенда c3, что и в тесте T7.137
C3_QUESTION = (
    "Какие прогнозы инфляции в России на 2026 год дают аналитики крупных банков "
    "(Сбербанк, ВТБ, Альфа-Банк, Газпромбанк) и чем они отличаются от прогноза Банка России? "
    "Приведи прогноз каждого с источником и датой."
)


@pytest.mark.parametrize(
    ("query", "expected"),
    [
        # имя смешанного написания, которое раньше не матчалось вообще
        ("СберCIB прогноз инфляции в России 2026", ("Сбербанк",)),
        ("SberCIB прогноз безработицы в России 2026", ("Сбербанк",)),
        ("sbercib.ru прогноз инфляции 2026", ("Сбербанк",)),
        # косвенные падежи разговорной формы имени
        ("в Сбере ждут снижения ставки в 2026", ("Сбербанк",)),
        ("прогноз аналитиков Сбера по инфляции 2026", ("Сбербанк",)),
        ("обзор Сбера по инфляции 2026", ("Сбербанк",)),
        # единственное число «Центральный банк» без «России» = Банк России
        ("Центральный банк повысил прогноз инфляции", ("Банк России",)),
        ("прогноз Центрального банка на 2026 год", ("Банк России",)),
        ("регуляторика Центрального банка России 2026", ("Банк России",)),
        # короткая форма министерства
        ("Минэк повысил прогноз инфляции 2026", ("Минэкономразвития",)),
        ("прогноз Минэка по инфляции 2026", ("Минэкономразвития",)),
        # полные формы латиницей
        ("Alfa-Bank прогноз инфляции 2026", ("Альфа-Банк",)),
        ("Gazprombank прогноз инфляции 2026", ("Газпромбанк",)),
    ],
)
def test_names_that_were_missed_are_now_found(query: str, expected: tuple[str, ...]) -> None:
    assert named_query_actors(query) == expected


@pytest.mark.parametrize(
    "query",
    [
        # усечённая основа неоднозначна: это не названный актор каталога
        "Газпром нефть отчиталась о добыче 2026",
        "акции Газпрома выросли в 2026",
        "годовая отчётность Газпром нефти 2026",
        "альфа-коэффициент доходности портфеля 2026",
        "альфа и бета стратегии инвестирования 2026",
        # продукт другой организации — не Сбербанк
        "сберИндекс понизил прогноз инфляции 2026",
        "Сбер индекс потребительской активности 2026",
        "данные СберИндекса о тратах россиян 2026",
        # множественное число — не один названный актор
        "Центральные банки Азии повысили ставки",
        "банки России выдали кредиты малому бизнесу",
        "центральные банки публикуют прогнозы",
    ],
)
def test_false_hits_are_gone(query: str) -> None:
    assert named_query_actors(query) == ()


def test_bare_words_still_name_nothing() -> None:
    """«банк», «банк России» во множественном числе и «альфа» сами по себе акторами не
    становятся: шаблон требует имени целиком."""
    assert named_actors("банк повысил ставку") == ()
    assert named_actors("банк России опубликовал данные") == ("Банк России",)
    assert named_actors("Альфа выпустила отчёт") == ()


def test_c3_question_actor_order_is_unchanged() -> None:
    """Каталог и порядок названных акторов вопроса не изменились: тот же вопрос — тот же
    перечень, из которого гейт считает `MULTI_ACTOR_MIN`."""
    assert named_question_actors(C3_QUESTION) == (
        "Банк России",
        "Сбербанк",
        "ВТБ",
        "Альфа-Банк",
        "Газпромбанк",
    )
    assert MULTI_ACTOR_MIN == 3
    assert SEPARATE_SEARCH_MAX_ACTORS == 2


def test_sberbank_bridge_forms_are_the_catalogs_own() -> None:
    """Формы имени для моста витрины (T7.138 2б) берёт у этого же закрытого шаблона:
    «Сбербанк», «Сбера», «Сбере» — да; «СберИндекс» и «SberIndex» — нет."""
    assert names_sberbank("Сбербанк повысил прогноз")
    assert names_sberbank("прогноз аналитиков Сбера")
    assert names_sberbank("экономисты в Сбере ждут")
    assert names_sberbank("СберCIB понизил прогноз")
    assert not names_sberbank("СберИндекс понизил прогноз")
    assert not names_sberbank("данные SberIndex о тратах")
    assert not names_sberbank("")


def test_mixed_forms_do_not_double_the_actor() -> None:
    """Один запрос может назвать банк и полным именем, и смешанной формой: актор
    называется один раз, счётчик гейта не завышается."""
    assert named_query_actors("Сбербанк CIB СберCIB Сбер прогноз инфляции 2026") == ("Сбербанк",)
