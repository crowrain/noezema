"""Unit (T7.121a часть д1, т1 и т7): датировочная строка подтверждает период только
внутри предложения, где стоит значение.

Дефект пробы менеджера (ADR-0038 §8 д1): штампованное «день+месяц» в ТОЙ ЖЕ СТРОКЕ
предложения, где написано значение, подтверждает месяц; отдельная датировочная строка
(«14 октября 2026 года 11:46», «Москва. 14 октября.») — по-прежнему НЕ подтверждает:
стендовый finmarket-6727171 («октября» рядом со значением «2,2» написана только как
датировка публикации) остаётся отклонённым — т7 закрепляет это побайтовой страницей
фикстуры. Год уровня страницы (д2) датировочную строку не перебивает: month не
подтверждён в окне значения — страничная pairing не вызывается.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from apps.orchestrator import curator_period_gate as gate
from packages.domain.schemas.staging import ClaimProposal, ClaimType
from tests.unit.test_curator_period_gate_t7121 import C1_CREATED

pytestmark = pytest.mark.unit

REPO_ROOT = Path(__file__).resolve().parents[2]
FINMARKET_PAGE = (REPO_ROOT / "tests/fixtures/t7121/finmarket-6727171.normalized.txt").read_text(
    encoding="utf-8"
)


def _rejections(statement: str, *pages: str) -> dict[int, str]:
    claim = ClaimProposal(statement=statement, claim_type=ClaimType("external_fact"))
    return gate.claim_period_rejections(
        claims=[claim], texts_by_claim={0: list(pages)}, already_dropped=frozenset()
    )


# ── т1: штамп в предложении значения подтверждает месяц (красный на d9d5fd5) ────────


def test_stamp_in_value_sentence_confirms_month_t7121a() -> None:
    """«15 мая 2030 ... 7,8%» — единственное название месяца на странице штампованное,
    но стоит в той же строке предложения, где написано значение: период подтверждён
    (T7.121a д1). На d9d5fd5 любой штамп отбрасывался — утверждение отклонялось."""
    statement = "Рост конкуренции соискателей на вакансии в Тармении в мае 2030 года составил 7,8%."
    page = (
        "Сервис «Гелиос»: 15 мая 2030 года рост конкуренции соискателей — ровно 7,8% за месяц. "
        "Методика наблюдения — ежемесячная, ряды пересмотрены."
    )
    assert _rejections(statement, page) == {}


def test_stamp_with_time_in_value_sentence_confirms_month_t7121a() -> None:
    """Тот же предел для полного датировочного штампа со временем: «9 октября 2031 года
    11:46 служба зафиксировала ... 7,8%» — штамп и значение в одной строке предложения."""
    statement = "Рост конкуренции соискателей в Тармении в октябре 2031 года составил 7,8%."
    page = "9 октября 2031 года 11:46 служба «Гелиос» зафиксировала рост конкуренции на 7,8%."
    assert _rejections(statement, page) == {}


# ── граница д1: датировочная строка отдельна — подтверждения нет ────────────────────


def test_own_line_dateline_does_not_confirm_period_t7121a() -> None:
    """Штамп со временем отдельной строкой, значение — в другой строке: month не
    подтверждён, страница не вызывает даже год уровня страницы (д2 не запускается без
    подтверждённого месяца в окне)."""
    statement = "Рост конкуренции соискателей в Тармении в октябре 2030 года составил 7,8%."
    page = (
        "9 октября 2030 года 11:46\n"
        "Служба «Гелиос» зафиксировала рост конкуренции соискателей ровно на 7,8% за месяц."
    )
    reason = _rejections(statement, page)
    assert list(reason) == [0]
    assert "период «октябре 2030»" in reason[0]


def test_short_dateline_sentence_bounded_by_dots_t7121a() -> None:
    """«Москва. 9 октября. Служба — обзор.» — короткая датировочная строка резана точками:
    фрагмент со штампом не содержит значения, подтверждения нет (та же форма, что
    «Москва. 14 октября. INTERFAX.RU -…» на стенде)."""
    statement = "Рост конкуренции соискателей в Тармении в октябре 2030 года составил 7,8%."
    page = (
        "Москва. 9 октября. Служба «Гелиос» — еженедельный обзор рынка труда.\n"
        "Рост конкуренции соискателей — ровно 7,8% за месяц."
    )
    reason = _rejections(statement, page)
    assert list(reason) == [0]
    assert "период «октябре 2030»" in reason[0]


# ── д1 не сужает прежнее подтверждение: голое название месяца по-прежнему работает ──


def test_bare_month_near_value_still_confirms_t7121a() -> None:
    """Голое название месяца в окне значения с годом в окне — подтверждение прежнее
    (д1 убирает только датировочные строки, не легитимные названия периода)."""
    statement = "Рост конкуренции соискателей в Тармении в октябре 2030 года составил 7,8%."
    page = "Обзор «Гелиос»: в октябре 2030 года рост конкуренции — ровно 7,8%. Данные за год."
    assert _rejections(statement, page) == {}


# ── т7: стендовая finmarket-страница (побайтовая фикстура) не подтверждает «октябрь» ──


def test_finmarket_datelines_never_confirm_october_t7121a() -> None:
    """Тот же случай, что в пробе менеджера (e5a64868 / C1_CREATED): на побайтовой
    finmarket-странице «14 октября 2026 года 11:46», «14 октября.» и «11:45, 14 октября
    2026» — датировки статей; в предложениях со значением «2,2» месяца нет. Отказ
    по периоду сохранялся и до, и после T7.121a — закреплено здесь отдельно от пробы."""
    reason = _rejections(C1_CREATED, FINMARKET_PAGE)
    assert list(reason) == [0]
    assert "период «октябре 2026»" in reason[0]
    # датировочный штамп не просочился ни в какую группу причин как подтверждение;
    # отдельного отказа по дате документа у этой формулировки нет (маркеров «от/опубликовано» нет)
    assert "дата документа" not in reason[0]
