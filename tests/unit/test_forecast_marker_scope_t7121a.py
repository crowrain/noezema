"""Unit (T7.121a часть д4, т4): маркер прогноза — только когда само значение формулировки
есть прогноз, а не сравнение факта с чужими прогнозами и не глагол измерения.

Дефект пробы менеджера (ADR-0038 §8 д4): «фактическая инфляция … оказалась НИЖЕ ВСЕХ
ПРОГНОЗОВ» (7cc2b578) и «мониторинг ОЦЕНИВАЕТ обеспеченность работников … при снижении
ожиданий» (fc8720df) не являются прогнозами: первые значения — состоявшийся факт, второй —
измерение. Правила д4: сравнение факта с прогнозом гасит маркер (`_FACT_VS_FORECAST_RE`),
«оцен*» — маркер только в паре со сказуемым будущего (`_EVAL_FUTURE_FORMS`: «добавит»,
«вырастут»); имена показателей опросов («ожидания населения») маркерами не были и остаются.
Новых словарей нормализации нет — закрытые списки прежние, дополнен только будущий залог.
Нарезка закреплена на реальных стендовых формулировках фикстуры и на вымышленных парах.
"""

from __future__ import annotations

import pytest

from apps.orchestrator import curator_period_gate as gate
from tests.unit.test_curator_period_gate_t7121 import C2_VTB

pytestmark = pytest.mark.unit

# реальные формулировки стендовой фикстуры (tests/fixtures/t7121a/stand_claims_with_pages.jsonl)
STAND_NOT_FORECAST = {
    # «оказалась ниже всех прогнозов» — факт 5,59% сопоставлен с чужими прогнозами
    "7cc2b578": (
        "Фактическая годовая инфляция в России по итогам 2025 года (5,59%) оказалась ниже всех "
        "прогнозов аналитиков: прогноз Банка России — 6,5–7%, Минэкономразвития — 6,8%, "
        "консенсус-прогноз ЦБ — 6,6%"
    ),
    # «оценивает обеспеченность работников» — измерение мониторинга ЦБ, «ожиданий» — имя показателя
    "fc8720df": (
        "Мониторинг предприятий Банка России за Q2 2026 года оценивает обеспеченность работниками "
        "в -19,7 пункта (дефицит персонала), улучшая динамику с -30,6 в Q1 2025, при снижении "
        "ожиданий изменения численности до 1,1 пункта."
    ),
}
STAND_FORECAST = {
    # «оценивает, что повышение НДС добавит 1,5%» — оценка того, что БУДЕТ
    "7d810f8c": (
        "Софья Донец из Т-Инвестиций оценивает, что повышение НДС добавит 1,5% к инфляции на "
        "горизонте 5-6 месяцев в 2026 году."
    ),
    # «оценивает, что цены вырастут на дополнительные 2%» — то же
    "e61b4a58": (
        "Евгений Егоров из ACI Russia оценивает, что цены вырастут на дополнительные 2% "
        "из-за налоговых инициатив в 2026 году."
    ),
    # «повысил прогноз инфляции … до 6–7%» — значение формулировки есть сам прогноз
    "83590565": "Банк России повысил прогноз инфляции на 2026 год до 6–7%.",
}


def test_closed_stand_cases_marker_flags() -> None:
    """Маркерные флаги стендовых формулировок фикстуры (всё множество разбора зафиксировано)."""
    for cid, statement in STAND_NOT_FORECAST.items():
        assert not gate.has_forecast_marker(statement), cid
    for cid, statement in STAND_FORECAST.items():
        assert gate.has_forecast_marker(statement), cid
    # прежнее поведение T7.121 не ослаблено: прогноз ВТБ 5–6% — маркер
    assert gate.has_forecast_marker(C2_VTB)


def test_eval_verb_only_marks_with_future_predicate_t7121a() -> None:
    """Пара «оцен* + будущее сказуемое» — маркер; «оцен* + прошедшее» — измерение, не маркер."""
    future = "Служба «Веер» даёт оценку: инфляция в Тармении вырастет до 5,0% к концу 2031 года."
    past = "Служба «Веер» оценивает годовую инфляцию в Тармении: по итогам 2030 года она выросла на 4,3%."
    assert gate.has_forecast_marker(future)
    assert not gate.has_forecast_marker(past)


def test_fact_vs_forecast_comparison_never_marks_t7121a() -> None:
    """Сравнение состоявшегося значения с прогнозами/ожиданиями/консенсусом — не маркер,
    даже когда слова «прогноз» и «консенсус» в формулировке есть."""
    variants = (
        "Индекс делового климата службы «Веер» в Тармении в июне 2031 года составил 8,7% — "
        "выше прогнозов участников опроса (6,5%).",
        "Фактическая инфляция в Тармении за 2030 год оказалась ниже консенсус-прогноза: "
        "прогноз службы «Веер» — 6,5%.",
        "Рост конкуренции соискателей уступил ожиданиям аналитиков: факт — 7,8% к июню 2031 года.",
    )
    for statement in variants:
        assert not gate.has_forecast_marker(statement), statement


def test_poll_indicator_nouns_stay_non_markers() -> None:
    """Имена показателей опросов («инфляционные ожидания населения») — не маркер (предел
    T7.121 сохранён): «выросли» — прошедшее время, залогового списка нет."""
    statement = "Инфляционные ожидания населения Тармении в сентябре 2031 года выросли до 15,1%."
    assert not gate.has_forecast_marker(statement)
