"""Unit (T7.121a часть д2, т2): год подтверждается страницей целиком, когда месяц уже
подтверждён рядом со значением.

Дефект пробы менеджера (дополнение ADR-0038 §11, д2): «в сентябре 2026 ... 15,1%» на cbr-странице —
месяц стоит в окне значения, но год написан только в строке выпуска «№ 9 (117), сентябрь
2026 года» далеко от значения. Год берётся с уровня страницы pairing-подписью: строка,
называющая месяц вплотную с этим годом, либо датировочная запись месяца с явным годом
(«29 сентября 2026 года»). Одиночный год где-то на странице — НЕ подтверждение;
pairing месяца с годом без подтверждённого в окне значения месяца силы не имеет
(случай 6d9a12ff: шапка «в декабре 2025 года» есть, но ни одно название декабря не лежит
в окне значения — отказ периода прежний). Конфликт: если
название того же месяца в окне значения назвало ДРУГОЙ год, страница окно не перебивает.
"""

from __future__ import annotations

import pytest

from apps.orchestrator import curator_period_gate as gate
from packages.domain.schemas.staging import ClaimProposal, ClaimType

pytestmark = pytest.mark.unit

_FILLER = "Методическая справка службы. Пересмотр рядов, веса индексов, пояснения методики. " * 8


def _rejections(statement: str, page: str) -> dict[int, str]:
    claim = ClaimProposal(statement=statement, claim_type=ClaimType("external_fact"))
    return gate.claim_period_rejections(
        claims=[claim], texts_by_claim={0: [page]}, already_dropped=frozenset()
    )


STATEMENT = "Наблюдаемая населением инфляция в Тармении в сентябре 2031 года выросла до 15,1%."


# ── год из строки выпуска далеко от значения (красный на d9d5fd5) ────────────────────


def test_issue_line_year_outside_window_confirms_t7121a() -> None:
    """Месяц голом в окне значения, года в окне нет — строка выпуска «№ 9 (117), сентябрь
    2031 года» за пределами окна подтверждает год (T7.121a д2; стенд 7c8c9afe)."""
    page = (
        f"Наблюдаемая инфляция населения в сентябре выросла до ровно 15,1%.\n{_FILLER}\n"
        "Выпуск № 9 (117), сентябрь 2031 года."
    )
    assert _rejections(STATEMENT, page) == {}


def test_dated_month_record_outside_window_confirms_t7121a() -> None:
    """Вариант pairing-подписи — датировочная запись месяца с явным годом («29 сентября
    2031 года») далеко от значения."""
    page = (
        f"Наблюдаемая инфляция населения в сентябре выросла до ровно 15,1%.\n{_FILLER}\n"
        "Данные обновлены 29 сентября 2031 года."
    )
    assert _rejections(STATEMENT, page) == {}


def test_pairing_with_other_year_does_not_confirm_t7121a() -> None:
    """Pairing-строка называет месяц с ДРУГИМ годом (2030) — подтверждения нет: год берётся
    только в паре с тем же месяцем."""
    page = (
        f"Наблюдаемая инфляция населения в сентябре выросла до ровно 15,1%.\n{_FILLER}\n"
        "Выпуск № 9 (117), сентябрь 2030 года."
    )
    reason = _rejections(STATEMENT, page)
    assert "период «сентябре 2031»" in reason[0]


# ── конфликт месяца в окне значения блокирует страничный год ────────────────────────


def test_conflicting_month_year_in_window_blocks_page_year_t7121a() -> None:
    """В окне значения тот же месяц назван с другим годом («в сентябре 2030 года … 14,9») —
    страница окно не перебивает, хотя pairing-строка с 2031 законна (честность д2)."""
    page = (
        "Наблюдаемая инфляция населения в сентябре выросла до ровно 15,1%.\n"
        "Для сравнения: в сентябре 2030 года тот же индекс составлял 14,9%.\n"
        f"{_FILLER}\nВыпуск № 9 (117), сентябрь 2031 года."
    )
    reason = _rejections(STATEMENT, page)
    assert "период «сентябре 2031»" in reason[0]


# ── одиночный год на странице недостаточен; pairing без оконного месяца — тоже ───────


def test_bare_year_without_month_pairing_is_not_confirmation_t7121a() -> None:
    """Синтетический случай уровня 6d9a12ff («декабре 2025», опрос «инФОМ»): месяц в окне
    значения без года, на странице — одиночные годы и «ноябрь», pairing-строки «декабрь …
    2030» нет — отказ по периоду остаётся. (В самом 6d9a12ff pairing шапки «в декабре 2025
    года» есть, но названия декабря не лежат в окне значения — разбор в
    test_stand_fixture_table_t7121a и дополнении ADR-0038 §11.)"""
    statement = "Индекс потребительских настроений в Тармении в декабре 2030 года составил 13,1%."
    page = (
        "Опрос службы: в декабре индекс опустился до ровно 13,1% — ниже уровня ноября.\n"
        f"{_FILLER}\nГодовой обзор 2030 года и итоги 2029 года опубликованы отдельно.\n"
        "Тарменский статистический бюллетень, выпуск за ноябрь 2030 года."
    )
    reason = _rejections(statement, page)
    assert "период «декабре 2030»" in reason[0]
