"""Unit (T7.121a часть д3, т3): названная дата документа обязана существовать на странице
целиком, а не рядом со значением; период значения — по-прежнему в окне значения.

Дефект пробы менеджера (ADR-0038 §8 д3): «опубликовано 16–21 января 2026 г.» в скобке
формулировки — ДАТА ДОКУМЕНТА, а не период значения: она проверяется по всей странице
(стендовая 9266248e подтвердилась строкой «Скачать / 21 января 2026 года» далеко от
значения), и отсутствующая названная дата снимает операцию отдельной именованной
причиной «дата документа «…» не найдена на связанной странице». Маркеры даты
документа — закрытые: «от …», «опубликов* …», «по состоянию на …»; «за сентябрь 2026»
маркером не является.
"""

from __future__ import annotations

import pytest

from apps.orchestrator import curator_period_gate as gate
from packages.domain.schemas.staging import ClaimProposal, ClaimType

pytestmark = pytest.mark.unit

_FILLER = "Методическая справка службы. Пересмотр рядов, веса индексов, пояснения методики. " * 8


def _rejections(statement: str, *pages: str) -> dict[int, str]:
    claim = ClaimProposal(statement=statement, claim_type=ClaimType("external_fact"))
    return gate.claim_period_rejections(
        claims=[claim], texts_by_claim={0: list(pages)}, already_dropped=frozenset()
    )


DOC_CLAIM = (
    "Инфляция в Тармении по итогам 2030 года (декабрь 2030 к декабрю 2029) составила 7,8% "
    "(служба «СтатТарм», опубликовано 16–21 января 2031 г.)."
)
_VALUE_PAGE = (
    "Ежемесячный бюллетень «СтатТарм»: инфляция по итогам 2030 года — за декабрь 2030 года "
    "к декабрю 2029 года ровно 7,8%."
)


def test_doc_tokens_are_flagged_not_value_periods_t7121a() -> None:
    """Токены формулировки: «21 января 2031» после «опубликовано 16–» — дата документа;
    целевая фраза и месяцы сравнения — периоды значения."""
    kinds = {
        (token.kind, token.label): token.doc_date
        for token in gate.statement_period_tokens(DOC_CLAIM)
    }
    assert kinds[("date", "21 января 2031")] is True
    assert kinds[("target", "по итогам 2030 года")] is False
    assert kinds[("month", "декабрь 2030")] is False
    assert kinds[("month", "декабрю 2029")] is False


def test_doc_date_confirmed_far_from_value_t7121a() -> None:
    """«21 января 2031 года» — на отдельной строке далеко от значения (стенд 9266248e).
    На d9d5fd5 это был период, требуемый рядом со значением, — утверждение отклонялось."""
    page = f"{_VALUE_PAGE}\n{_FILLER}\nСкачать выпуск / 21 января 2031 года"
    assert _rejections(DOC_CLAIM, page) == {}


def test_doc_date_on_other_linked_page_counts_t7121a() -> None:
    """Дата документа ищется по всем оставшимся связям `supports`: подтверждается на второй
    странице, где значения утверждения нет вовсе (окно значения там пустое)."""
    assert _rejections(DOC_CLAIM, _VALUE_PAGE, f"{_FILLER}\nПресс-релиз от 21 января 2031 года") == {}


def test_missing_doc_date_rejected_with_named_reason_t7121a() -> None:
    """Названной даты нигде на страницах нет — снятие отдельной причиной «дата документа …»
    (на d9d5fd5 причина называла это «периодом»)."""
    reason = _rejections(DOC_CLAIM, f"{_VALUE_PAGE}\n{_FILLER}")
    assert "дата документа «21 января 2031» не найдена на связанной странице" in reason[0]
    # в группу периодов дата документа не попадает: «период «…»» в причине отсутствует
    assert "период «" not in reason[0]


def test_doc_month_with_year_confirmed_by_pairing_line_anywhere_t7121a() -> None:
    """Дата документа «по состоянию на февраль 2031 года» подтверждается названием месяца
    с этим годом на ЛЮБОЙ строке страницы — окно значения ни при чём (стендовая форма
    «по состоянию на февраль 2026» в скобках формулировки)."""
    statement = "Деловой климат в Тармении по состоянию на февраль 2031 года — индекс 8,7%."
    page = (
        f"Индекс делового климата службы «Веер»: февраль 2031 — ровно 8,7%.\n{_FILLER}\n"
        "Опрос проведён до конца февраля."
    )
    # токен — дата документа (не период значения); подтверждён названием месяца с этим годом
    # на любой строке, окно значения ни при чём
    assert _rejections(statement, page) == {}


def test_year_doc_month_needs_pairing_not_bare_year_t7121a() -> None:
    """Дата документа с годом требует pairing-подписи (месяц вплотную с этим годом либо
    строка месяца с этим годом), одиночный год на странице недостаточен."""
    statement = "Деловой климат в Тармении по состоянию на февраль 2031 года — индекс 8,7%."
    page = (
        "Индекс делового климата службы «Веер»: в феврале индекс составил ровно 8,7%.\n"
        f"{_FILLER}\nГодовой обзор 2031 года опубликован отдельно."
    )
    reason = _rejections(statement, page)
    assert "дата документа «февраль 2031»" in reason[0]


def test_loose_stamp_year_from_page_title_t7121a() -> None:
    """Штамп страницы без явного года («17:00, 26 февраля») подтверждает названную дату
    «26 февраля 2031 года», если год написан на странице целиком (заголовок «…в 2031
    году») — тот же механизм, что у стенда c263e93c/YSIA."""
    statement = (
        "Индекс делового климата в Тармении — 8,7% (прогноз от 26 февраля 2031 года)."
    )
    page = (
        "Служба «Веер»: прогноз делового климата в 2031 году.\n"
        "Обновлено в 17:00, 26 февраля\n"
        "Индекс делового климата: в феврале — ровно 8,7%."
    )
    assert _rejections(statement, page) == {}


def test_conflicting_explicit_year_on_stamp_rejects_doc_date_t7121a() -> None:
    """Дата-строка страницы называет то же «26 февраля» с другим годом (2030) — названная
    дата 2031 на странице не подтверждена."""
    statement = "Индекс делового климата в Тармении — 8,7% (прогноз от 26 февраля 2031 года)."
    page = (
        "Служба «Веер»: индекс делового климата — ровно 8,7% за месяц.\n"
        "Обновлено 26 февраля 2030 года в 17:00."
    )
    reason = _rejections(statement, page)
    assert "дата документа «26 февраля 2031 года»" in reason[0]


def test_period_after_preposition_needs_window_confirmation_t7121a() -> None:
    """«за сентябрь 2031 года» — не маркер даты документа: период значения обязан
    подтверждаться в окне значения, как и раньше (стенд 2f456e85)."""
    statement = "Индекс конкуренции службы «Веер» за сентябрь 2031 года составил 8,7%."
    page = f"Конкуренция соискателей — ровно 8,7% за месяц.\n{_FILLER}\nОпрос проведён за сентябрь 2031 года."
    reason = _rejections(statement, page)
    assert "период «сентябрь 2031»" in reason[0]
    assert "дата документа" not in reason[0]
