"""T7.85a: вето «другой источник числа» в окне публикации (замечание приёмки T7.85, ADR-0029).

Дефект, найденный менеджером при приёмке на `792d2c4`: режим «окно публикации» проверял маркер
публикации, атрибуцию и число названных первоисточников в окне, но НЕ проверял, не появился ли
МЕЖДУ фразой атрибуции и числом другой источник этого числа — другое действующее лицо, чья-то
оценка, прогноз или чужое исследование. Следствие: фраза «аналитики Сбербанка ожидают 6,3% после
упоминания опубликованного отчёта Росстата» приписывалась Росстату; «экономисты Райффайзенбанка
оценивают 14,5% после упомянутого опроса ЦБ» — Банку России.

Правило FIX: в окне публикации (и только в нём; строгий режим не тронут) приписывание запрещено,
если между концом фразы атрибуции публикации и числом (включая предложение с числом) есть хоть
один признак другого источника числа: действующее лицо (аналитики, экономисты, эксперты, компания,
исследование…), глагол или оборот оценки/прогноза (оценивают, считают, по оценке, по мнению), либо
название в кавычках, отсутствующее в словаре первоисточников. Сомнение — не приписывать: pairing
не срабатывает, остаётся честный отказ строгого режима.

Различение имени показателя и чужой оценки (форма Коммерсанта): «Оценка текущих темпов роста цен
… осталась на уровне 14,5%» — существительное «оценка» здесь NAME published indicator'a, а не
действие над значением: вето требует глагольной формы («оценивают», «оценил») или оборота
«по оценке» и НЕ срабатывает на голое существительное. Тот же разбор для «ожиданий»:
«Показатель ожидаемой инфляции вырос» — имя показателя; «экономисты ожидают 6,3%» — чужой прогноз.

Строгие формы «Банк России/Банка России» не считаются действующим лицом-банком: алиасы словаря
нейтрализуются перед поиском признака «банк».
"""

from __future__ import annotations

import pytest

from apps.research_proxy.value_attribution import (
    PAIRING_PUBLICATION_WINDOW,
    PAIRING_VALUE_AND_PRIMARY,
    VALUE_ATTRIBUTION_METHOD_VERSION,
    attribute_value_in_fragment,
)

pytestmark = pytest.mark.unit

NEWS_URI = "https://news.example.ru/a"


def _decide(text: str, claim: str) -> object:
    return attribute_value_in_fragment(
        canonical_uri=NEWS_URI, text=text, claim_statement=claim
    )


# ─── дефект приёмки: смена источника внутри окна публикации ──────────────────────────


@pytest.mark.parametrize(
    ("text", "claim", "expected_status"),
    [
        # (1) публикация Росстата названа у 5,59%, а 6,3% — чужой прогноз («аналитики Сбербанка
        # ожидают»): действующее лицо + глагол ожидания между атрибуцией и числом
        (
            "По данным опубликованного Росстатом отчёта, инфляция в 2025 году составила 5,59%. "
            "Аналитики Сбербанка ожидают инфляцию 6,3% в 2026 году.",
            "Аналитики Сбербанка ожидают инфляцию 6,3% в 2026 году.",
            "value_not_attributed",
        ),
        # (2) опубликованный ЦБ опрос назван, но 14,5% оценивает другое действующее лицо
        (
            "Согласно опубликованному Банком России опросу, ожидания выросли. "
            "Экономисты Райффайзенбанка оценивают реальную инфляцию в 14,5%.",
            "Реальная инфляция в 2025 году составила 14,5%.",
            "no_value_attribution",
        ),
        # (3) опубликованный ЦБ опрос назван, но 14,5% — результат чужого исследования («Ромир»)
        (
            "Как следует из опубликованного Банком России опроса, ожидания выросли до 13,7%. "
            "Исследование Ромир показало наблюдаемую инфляцию 14,5%.",
            "Наблюдаемая инфляция составила 14,5%.",
            "value_not_attributed",
        ),
    ],
)
def test_another_source_inside_publication_window_is_not_a_retelling(
    text: str, claim: str, expected_status: str
) -> None:
    decision = _decide(text, claim)
    assert not decision.is_derivative, decision
    assert decision.primary_key is None, decision
    assert decision.status == expected_status, decision
    # pairing остаётся строгим: оконное решение не состоялось, честный отказ сохраняется
    assert decision.pairing == PAIRING_VALUE_AND_PRIMARY, decision


# ─── правильные формы T7.85 не сломаны ────────────────────────────────────────────────


def test_own_assessment_still_wins() -> None:
    """(4) «По нашим расчётам» — вето собственной оценки действует и после правки."""
    decision = _decide(
        "Согласно опубликованному Банком России опросу, ожидания выросли. "
        "По нашим расчётам, наблюдаемая инфляция составила 14,5%.",
        "Наблюдаемая инфляция составила 14,5%.",
    )
    assert decision.status == "own_assessment", decision


def test_two_named_primaries_stay_ambiguous() -> None:
    """(5) два названных первоисточника в окне — по-прежнему честный ambiguous, а не derivative."""
    decision = _decide(
        "По данным опроса Росстата, инфляция составила 5,59%. Аналитики ЦБ прогнозируют 6,3%.",
        "Прогноз инфляции 6,3%.",
    )
    assert decision.status == "ambiguous_primaries", decision
    assert not decision.is_derivative, decision
    assert decision.pairing == PAIRING_PUBLICATION_WINDOW, decision


def test_kommersant_form_indicator_noun_stays_derivative() -> None:
    """(6) форма Коммерсанта: «Оценка текущих темпов роста цен … осталась на уровне 14,5%» —
    существительное «оценка» здесь имя показателя, а не чья-то оценка: приписывание ЦБ остаётся."""
    decision = _decide(
        "Об этом следует из опубликованных 17 декабря данных опроса, проводимого «инФОМ» "
        "по заказу Банка России. Оценка текущих темпов роста цен при этом осталась на уровне 14,5%.",
        "Наблюдаемая населением годовая инфляция в декабре 2025 года составила 14,5%.",
    )
    assert decision.is_derivative, decision
    assert decision.primary_key == "cbr", decision.basis_fragment
    assert decision.pairing == PAIRING_PUBLICATION_WINDOW, decision


def test_expectations_inside_the_attribution_sentence_are_not_a_veto() -> None:
    """«ожидания выросли до 13,7%» внутри самой фразы атрибуции — не другой источник числа:
    это то, что сообщает опубликованный опрос ЦБ. Вето начинается после конца фразы."""
    decision = _decide(
        "Как следует из опубликованного Банком России опроса, ожидания выросли до 13,7%. "
        "Текущая оценка инфляции при этом осталась на уровне 14,5%.",
        "Наблюдаемая инфляция составила 14,5%.",
    )
    assert decision.is_derivative, decision
    assert decision.primary_key == "cbr", decision.basis_fragment
    assert decision.pairing == PAIRING_PUBLICATION_WINDOW, decision


def test_bank_of_russia_alias_is_not_an_actor_bank() -> None:
    """«Банк России» после фразы атрибуции — первоисточник, а не действующее лицо-банк:
    алиасы словаря нейтрализуются перед поиском признака «банк»."""
    decision = _decide(
        "Как следует из опубликованного Банком России опроса, ожидания выросли. "
        "Банк России сохранил оценку текущих темпов на уровне 14,5%.",
        "Наблюдаемая инфляция составила 14,5%.",
    )
    assert decision.is_derivative, decision
    assert decision.primary_key == "cbr", decision.basis_fragment


# ─── варианты из замечания приёмки: все «не derivative» ──────────────────────────────


@pytest.mark.parametrize(
    ("text", "claim", "expected_status"),
    [
        # «по оценке ВШЭ»: оборот чужой оценки + название вне словаря
        (
            "Согласно опубликованному Банком России опросу, ожидания выросли. "
            "По оценке ВШЭ, реальная инфляция составила 14,5%.",
            "Реальная инфляция составила 14,5%.",
            "no_value_attribution",
        ),
        # «Независимые экономисты считают…»: действующее лицо + глагол мнения
        (
            "Как сообщил Банк России результаты опроса, ожидания выросли до 13,7%. "
            "Независимые экономисты считают реальную инфляцию в 14,5%.",
            "Реальная инфляция составила 14,5%.",
            "value_not_attributed",
        ),
        # «Компания «Ромир» зафиксировала…»: действующее лицо + название в кавычках вне словаря
        (
            "Согласно опубликованному Банком России опросу, ожидания выросли. "
            "Компания «Ромир» зафиксировала наблюдаемую инфляцию на уровне 14,5%.",
            "Наблюдаемая инфляция составила 14,5%.",
            "no_value_attribution",
        ),
        # «эксперты ЦМАКП рассчитали…»: действующее лицо + глагол расчёта
        (
            "Согласно опубликованному Банком России опросу, инфляционные ожидания выросли. "
            "Эксперты ЦМАКП рассчитали наблюдаемую инфляцию в 14,5%.",
            "Наблюдаемая инфляция составила 14,5%.",
            "no_value_attribution",
        ),
        # «по мнению аналитиков»: оборот мнения + действующее лицо
        (
            "Как следует из опубликованного Росстатом отчёта, инфляция замедлилась. "
            "По мнению аналитиков, точная оценка — 14,5%.",
            "Оценка инфляции составила 14,5%.",
            "no_value_attribution",
        ),
    ],
)
def test_actor_or_estimate_sign_refuses_pairing(
    text: str, claim: str, expected_status: str
) -> None:
    decision = _decide(text, claim)
    assert not decision.is_derivative, decision
    assert decision.primary_key is None, decision
    assert decision.status == expected_status, decision
    assert decision.pairing == PAIRING_VALUE_AND_PRIMARY, decision


